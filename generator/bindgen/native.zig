//! Native structure declarations from `native_structures`.

pub fn generate(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const class_resolver.ClassResolver,
) !void {
    const path = try std.fs.path.join(arena, &.{ options.output_dir, "native.zig" });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create native structures file `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush native structures file `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;
    const real_name = types.realTypeName(options.api.builtin_build_conf);

    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    for (api.native_structures) |structure| {
        try writer.writeAll("pub const ");
        try names.writeRawIdent(writer, structure.name);
        try writer.writeAll(" = extern struct {\n");
        var members = std.mem.splitScalar(u8, structure.format, ';');
        while (members.next()) |member_text| {
            const member = parseMember(member_text) orelse continue;
            try writer.writeAll("    ");
            try names.writeRawIdent(writer, member.name);
            try writer.writeAll(": ");
            if (member.array_len) |length| try writer.print("[{d}]", .{length});
            try writeNativeType(writer, api, resolver, member.raw_type, member.pointer, real_name);
            try writer.writeAll(",\n");
        }
        try writer.writeAll("};\n\n");
    }

    const sections = (try custom_code.readForOutput(arena, io, "native.zig")) orelse custom_code.Sections{};
    try custom_code.writeRaw(writer, sections.namespace_code);
    try writer.writeAll("const builtins = @import(\"builtins/builtins.zig\");\n");
    try writer.writeAll("const classes = @import(\"classes/classes.zig\");\n");
}

const Member = struct {
    name: []const u8,
    raw_type: []const u8,
    pointer: bool,
    array_len: ?usize = null,
};

fn parseMember(input: []const u8) ?Member {
    var text = std.mem.trim(u8, input, " \r\n");
    if (text.len == 0) return null;
    if (std.mem.indexOfScalar(u8, text, '=')) |equals| {
        text = std.mem.trim(u8, text[0..equals], " ");
    }

    var array_len: ?usize = null;
    if (std.mem.endsWith(u8, text, "]")) {
        if (std.mem.lastIndexOfScalar(u8, text, '[')) |open| {
            const digits = text[open + 1 .. text.len - 1];
            if (std.fmt.parseInt(usize, digits, 10)) |length| {
                array_len = length;
                text = std.mem.trim(u8, text[0..open], " ");
            } else |_| {}
        }
    }

    if (std.mem.indexOfScalar(u8, text, '*')) |star| {
        const raw_type = std.mem.trim(u8, text[0..star], " ");
        const name = std.mem.trim(u8, text[star + 1 ..], " ");
        if (raw_type.len == 0 or name.len == 0) return null;
        return .{ .name = name, .raw_type = raw_type, .pointer = true, .array_len = array_len };
    }

    const space = std.mem.lastIndexOfScalar(u8, text, ' ') orelse return null;
    const raw_type = std.mem.trim(u8, text[0..space], " ");
    const name = std.mem.trim(u8, text[space + 1 ..], " ");
    if (raw_type.len == 0 or name.len == 0) return null;
    return .{ .name = name, .raw_type = raw_type, .pointer = false, .array_len = array_len };
}

fn writeNativeType(
    writer: *Io.Writer,
    api: ExtensionApiJson,
    resolver: *const class_resolver.ClassResolver,
    raw_type: []const u8,
    pointer: bool,
    real_name: []const u8,
) !void {
    if (pointer) {
        if (resolver.get(raw_type)) |info| {
            try writeClassRef(writer, info);
            return;
        }
        if (isBuiltin(api, raw_type)) {
            try writer.print("builtins.{s}", .{raw_type});
            return;
        }
        try names.writeRawIdent(writer, raw_type);
        return;
    }

    if (std.mem.eql(u8, raw_type, "real_t")) return writer.writeAll(real_name);
    if (primitiveType(raw_type)) |zig_type| return writer.writeAll(zig_type);
    if (std.mem.eql(u8, raw_type, "ObjectID")) return writer.writeAll("ObjectID");
    if (isNative(api, raw_type)) {
        try names.writeRawIdent(writer, raw_type);
        return;
    }
    if (std.mem.indexOf(u8, raw_type, "::")) |separator| {
        const class_name = raw_type[0..separator];
        const enum_name = raw_type[separator + 2 ..];
        if (resolver.get(class_name)) |info| {
            try classesClassRef(writer, info);
            try writer.writeAll(".");
            try names.writeRawIdent(writer, enum_name);
            return;
        }
    }
    if (isBuiltin(api, raw_type)) {
        try writer.print("builtins.{s}", .{raw_type});
        return;
    }

    std.log.warn("Unknown native structure type `{s}`", .{raw_type});
    try names.writeRawIdent(writer, raw_type);
}

fn writeClassRef(writer: *Io.Writer, info: *const class_resolver.Info) !void {
    try writer.writeAll("*");
    try classesClassRef(writer, info);
}

fn classesClassRef(writer: *Io.Writer, info: *const class_resolver.Info) !void {
    try writer.writeAll("classes.");
    if (info.class.api_type) |api_type| {
        try common.writeIdent(writer, .snake, api_type);
        try writer.writeAll(".");
    }
    try names.writeRawIdent(writer, info.class.name);
}

fn primitiveType(raw_type: []const u8) ?[]const u8 {
    const primitives = .{
        .{ "bool", "bool" },
        .{ "char", "u8" },
        .{ "double", "f64" },
        .{ "float", "f32" },
        .{ "int", "i32" },
        .{ "int8_t", "i8" },
        .{ "int16_t", "i16" },
        .{ "int32_t", "i32" },
        .{ "int64_t", "i64" },
        .{ "uint8_t", "u8" },
        .{ "uint16_t", "u16" },
        .{ "uint32_t", "u32" },
        .{ "uint64_t", "u64" },
        .{ "uintptr_t", "usize" },
        .{ "void", "anyopaque" },
    };
    inline for (primitives) |entry| {
        if (std.mem.eql(u8, raw_type, entry[0])) return entry[1];
    }
    return null;
}

fn isNative(api: ExtensionApiJson, raw_type: []const u8) bool {
    for (api.native_structures) |structure| {
        if (std.mem.eql(u8, structure.name, raw_type)) return true;
    }
    return false;
}

fn isBuiltin(api: ExtensionApiJson, raw_type: []const u8) bool {
    for (api.builtin_classes) |builtin| {
        if (std.mem.eql(u8, builtin.name, raw_type)) return true;
    }
    return std.mem.eql(u8, raw_type, "Variant") or std.mem.eql(u8, raw_type, "Object");
}

