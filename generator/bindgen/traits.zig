//! Generated builtin classification.
//!
//! One source of truth for builtins that need special Variant handling. The
//! table is keyed by Godot class name so both raw binding types and codegen
//! builtin types can use it without importing each other.

const std = @import("std");
const Io = std.Io;
const Allocator = std.mem.Allocator;
const ExtensionApiJson = @import("../model/ExtensionApiJson.zig");
const api_options = @import("../model/api_options.zig");

pub const Kind = enum {
    plain,
    managed,
    packed_array,
    heap,
};

fn classify(name: []const u8, has_destructor: bool, size: usize, inline_capacity: usize) Kind {
    if (size > inline_capacity) return .heap;
    if (has_destructor and std.mem.startsWith(u8, name, "Packed")) return .packed_array;
    if (has_destructor) return .managed;
    return .plain;
}

fn primitive(name: []const u8) bool {
    inline for (.{ "Nil", "bool", "int", "float" }) |primitive_name| {
        if (std.mem.eql(u8, name, primitive_name)) return true;
    }
    return false;
}

pub fn generate(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    builtins_dir: []const u8,
    builtin_build_conf: api_options.BuiltinBuildConf,
) !void {
    const sizes = api.sizesFor(builtin_build_conf) orelse {
        std.log.err("No builtin class sizes for {s}", .{@tagName(builtin_build_conf)});
        return error.MissingBuildConfiguration;
    };
    var variant_size: ?usize = null;
    for (sizes) |size| {
        if (std.mem.eql(u8, size.name, "Variant")) variant_size = size.size;
    }
    const inline_capacity = (variant_size orelse {
        std.log.err("Builtin class sizes are missing Variant", .{});
        return error.MissingVariantSize;
    }) - 8;

    const path = try std.fs.path.join(arena, &.{ builtins_dir, "traits.zig" });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create builtin traits `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush builtin traits `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    try writer.writeAll("pub const Kind = enum { plain, managed, packed_array, heap };\n\n");
    try writer.writeAll("pub const Entry = struct { name: []const u8, kind: Kind };\n\n");
    try writer.writeAll("pub const entries = [_]Entry{\n");
    for (api.builtin_classes) |class| {
        if (primitive(class.name)) continue;
        var size: usize = 0;
        for (sizes) |entry| {
            if (std.mem.eql(u8, entry.name, class.name)) size = entry.size;
        }
        try writer.print("    .{{ .name = \"{s}\", .kind = .{s} }},\n", .{
            class.name,
            @tagName(classify(class.name, class.has_destructor, size, inline_capacity)),
        });
    }
    try writer.writeAll("};\n\n");
    try writer.writeAll(
        \\pub fn kindOf(comptime T: type) Kind {
        \\    if (@typeInfo(T) != .@"struct" and @typeInfo(T) != .@"opaque") return .plain;
        \\    if (!@hasDecl(T, "GodotClassName")) return .plain;
        \\    inline for (entries) |entry| {
        \\        if (std.mem.eql(u8, T.GodotClassName, entry.name)) return entry.kind;
        \\    }
        \\    return .plain;
        \\}
        \\
        \\pub fn isManagedBuiltin(comptime T: type) bool {
        \\    const kind = kindOf(T);
        \\    return kind == .managed or kind == .packed_array;
        \\}
        \\
        \\pub fn isPackedArray(comptime T: type) bool {
        \\    return kindOf(T) == .packed_array;
        \\}
        \\
        \\pub fn isHeapBuiltin(comptime T: type) bool {
        \\    return kindOf(T) == .heap;
        \\}
        \\
        \\const std = @import("std");
        \\
    );
}

test "classify builtins" {
    try std.testing.expectEqual(Kind.plain, classify("Vector2", false, 16, 16));
    try std.testing.expectEqual(Kind.managed, classify("String", true, 8, 16));
    try std.testing.expectEqual(Kind.packed_array, classify("PackedByteArray", true, 16, 16));
    try std.testing.expectEqual(Kind.heap, classify("Transform3D", false, 48, 16));
}
