//! Builtin-class binding emission for `extension_api.json`.
//!
//! One file per builtin class, laid out as `output_dir/builtins/<snake>.zig`.
//! Each file contains:
//!   * the `extern struct` with the members of the selected build configuration,
//!   * a comptime layout check,
//!   * namespace functions that dispatch through the GDExtension interface,
//!   * constructor and operator wrappers,
//!   * optional hand-written code from `generator/bindgen/custom/builtins/<snake>.zig`.

pub fn generate(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    catalog: *const builtin_catalog.BuiltinCatalog,
    resolver: *const class_resolver.ClassResolver,
) !void {
    const real_name = types.realTypeName(options.api.builtin_build_conf);
    const pointer_align = types.pointerAlign(options.api.builtin_build_conf);
    const offsets = api.offsetsFor(options.api.builtin_build_conf) orelse {
        std.log.err("No builtin_class_member_offsets entry for {s}", .{@tagName(options.api.builtin_build_conf)});
        return error.MissingBuildConfiguration;
    };

    const builtins_dir = try std.fs.path.join(arena, &.{ options.output_dir, "builtins" });
    Io.Dir.cwd().createDirPath(io, builtins_dir) catch |err| {
        std.log.err("Failed to create builtins directory `{s}`: {}", .{ builtins_dir, err });
        return err;
    };

    for (catalog.entries) |entry| {
        const class = if (entry.class != null)
            (resolver.builtinClass(entry.name) orelse {
                std.log.err("Missing builtin class metadata for {s}", .{entry.name});
                return error.MissingBuiltinClass;
            }).*
        else
            ExtensionApiJson.BuiltinClass{ .name = entry.name };
        const field_offsets = if (entry.class != null) findOffsets(offsets, entry.name) else null;
        try generateClass(arena, io, api, class, entry.size, field_offsets, real_name, pointer_align, catalog, resolver, builtins_dir);
    }

    try writeAggregator(arena, io, catalog, builtins_dir);
}

fn writeAggregator(
    arena: Allocator,
    io: Io,
    catalog: *const builtin_catalog.BuiltinCatalog,
    builtins_dir: []const u8,
) !void {
    const AggregatorEntry = struct {
        file_name: []const u8,
        type_name: []const u8,
    };
    var entries: [256]AggregatorEntry = undefined;
    var count: usize = 0;
    for (catalog.entries) |entry| {
        entries[count] = .{
            .file_name = try names.snake(arena, entry.name),
            .type_name = entry.name,
        };
        count += 1;
    }
    std.mem.sort(AggregatorEntry, entries[0..count], {}, struct {
        fn lessThan(_: void, a: AggregatorEntry, b: AggregatorEntry) bool {
            return std.mem.order(u8, a.file_name, b.file_name) == .lt;
        }
    }.lessThan);

    const path = try std.fs.path.join(arena, &.{ builtins_dir, "builtins.zig" });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create builtins aggregator `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush builtins aggregator `{s}`: {}", .{ path, err });
    };

    try streaming.interface.writeAll("// Generated by bindgen. Do not edit.\n\n");
    for (entries[0..count]) |entry| {
        try streaming.interface.print("pub const {s} = @import(\"{s}.zig\");\n", .{ entry.file_name, entry.file_name });
        try streaming.interface.print("pub const {s} = {s}.{s};\n", .{ entry.type_name, entry.file_name, entry.type_name });
    }
    const sections = (try custom_code.readForOutput(arena, io, "builtins/builtins.zig")) orelse custom_code.Sections{};
    try custom_code.writeRaw(&streaming.interface, sections.namespace_code);
}

fn generateClass(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    class: ExtensionApiJson.BuiltinClass,
    expected_size: usize,
    field_offsets: ?[]const ExtensionApiJson.MemberOffset,
    real_name: []const u8,
    pointer_align: usize,
    catalog: *const builtin_catalog.BuiltinCatalog,
    resolver: *const class_resolver.ClassResolver,
    builtins_dir: []const u8,
) !void {
    const bare_name = try names.snake(arena, class.name);
    const file_name = try std.mem.concat(arena, u8, &.{ bare_name, ".zig" });
    const path = try std.fs.path.join(arena, &.{ builtins_dir, file_name });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create builtin file `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush builtin file `{s}`: {}", .{ path, err });
    };

    try emitFile(&streaming.interface, arena, io, api, class, expected_size, field_offsets, real_name, pointer_align, catalog, resolver);
}

fn emitFile(
    writer: *Io.Writer,
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    class: ExtensionApiJson.BuiltinClass,
    expected_size: usize,
    field_offsets: ?[]const ExtensionApiJson.MemberOffset,
    real_name: []const u8,
    pointer_align: usize,
    catalog: *const builtin_catalog.BuiltinCatalog,
    resolver: *const class_resolver.ClassResolver,
) !void {
    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    try docs.write(writer, arena, class.brief_description, 0, "//!");
    try docs.write(writer, arena, class.description, 0, "//!");
    if (class.brief_description != null or class.description != null) try writer.writeAll("\n");

    try writeLayoutCheck(writer, class, expected_size, field_offsets);
    try writer.writeAll("\n");

    try writeStruct(writer, arena, api, class, field_offsets, expected_size, real_name, pointer_align);

    var body_aw: Io.Writer.Allocating = .init(arena);
    const body = &body_aw.writer;
    try body.writeAll("\n");
    for (class.methods) |method| {
        if (method.is_vararg) {
            try writeVarargMethod(body, arena, class, method, real_name, resolver);
            continue;
        }
        try writeMethod(body, arena, api, class, method, real_name, resolver);
    }
    for (class.constructors) |constructor| {
        try writeConstructor(body, arena, api, class, constructor, real_name, resolver);
    }
    for (class.operators) |operator| {
        try writeOperator(body, arena, api, class, operator, real_name, resolver);
    }
    if (class.has_destructor) {
        try writeDestructor(body, arena, class);
    }

    const relative_path = try std.fmt.allocPrint(arena, "builtins/{s}.zig", .{try names.snake(arena, class.name)});
    const sections = (try custom_code.readForOutput(arena, io, relative_path)) orelse custom_code.Sections{};

    try writeIndented(writer, body_aw.writer.buffered(), 4);
    try custom_code.writeIndented(writer, sections.codeForStruct(class.name), 4);
    try writer.print("}};\n\ncomptime {{\n    checkTypeLayout({s});\n}}\n", .{class.name});

    if (sections.namespace_code.len != 0) {
        try writer.writeAll("\n");
        try custom_code.writeRaw(writer, sections.namespace_code);
    }

    try writeImports(writer, arena, api, class, catalog, resolver);
}

fn writeLayoutCheck(
    writer: *Io.Writer,
    class: ExtensionApiJson.BuiltinClass,
    expected_size: usize,
    field_offsets: ?[]const ExtensionApiJson.MemberOffset,
) !void {
    try writer.writeAll("pub fn checkTypeLayout(comptime T: type) void {\n");
    try writer.print("    if (@sizeOf(T) != {d}) @compileError(std.fmt.comptimePrint(\"{s}: expected size {d}, found {{d}}\", .{{@sizeOf(T)}}));\n", .{ expected_size, class.name, expected_size });
    try writer.print("    if (@alignOf(T) != @alignOf({s})) @compileError(std.fmt.comptimePrint(\"{s}: expected alignment {{d}}, found {{d}}\", .{{@alignOf({s}), @alignOf(T)}}));\n", .{ class.name, class.name, class.name });
    if (field_offsets) |members| {
        for (members) |member| {
            try writer.print("    if (@offsetOf(T, \"{s}\") != {d}) @compileError(std.fmt.comptimePrint(\"{s}.{s}: expected offset {d}, found {{d}}\", .{{@offsetOf(T, \"{s}\")}}));\n", .{ member.member, member.offset, class.name, member.member, member.offset, member.member });
        }
    }
    try writer.writeAll("}\n");
}

fn writeIndented(writer: *Io.Writer, text: []const u8, indent: usize) !void {
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |line| {
        if (line.len == 0) {
            try writer.writeByte('\n');
            continue;
        }
        for (0..indent) |_| try writer.writeByte(' ');
        try writer.writeAll(line);
        try writer.writeByte('\n');
    }
}

fn writeStruct(
    writer: *Io.Writer,
    arena: Allocator,
    api: ExtensionApiJson,
    class: ExtensionApiJson.BuiltinClass,
    field_offsets: ?[]const ExtensionApiJson.MemberOffset,
    expected_size: usize,
    real_name: []const u8,
    pointer_align: usize,
) !void {
    _ = api;
    try writer.print("pub const {s} = extern struct {{\n", .{class.name});

    if (field_offsets) |members| {
        for (members) |member| {
            if (findMember(class, member.member)) |member_info| {
                try docs.write(writer, arena, member_info.description, 4, "///");
            }
            try writer.writeAll("    ");
            try names.writeRawIdent(writer, member.member);
            try writer.writeAll(": ");
            try types.writeMetaType(writer, member.meta, real_name);
            try writer.writeAll(",\n");
        }
    } else {
        try writer.print("    _opaque: [{d}]u8 align({d}),\n", .{ expected_size, pointer_align });
    }

    for (class.enums) |class_enum| {
        try writer.writeAll("\n");
        try enum_emit.write(writer, arena, class_enum, 4);
    }
}

fn writeBuiltinDefault(
    writer: *Io.Writer,
    raw_type: []const u8,
    default_value: []const u8,
    real_name: []const u8,
    resolver: *const class_resolver.ClassResolver,
) !bool {
    _ = real_name;
    if (try defaults.writeMathLiteral(writer, "", raw_type, default_value)) return true;
    if (try defaults.writeStringLiteral(writer, "", raw_type, default_value, "dispatcher")) return true;
    if (std.mem.eql(u8, raw_type, "Variant")) {
        if (try defaults.writeVariantLiteral(writer, "", default_value, "dispatcher")) return true;
    }
    if (try defaults.writeEmptyContainer(writer, "", raw_type, default_value, "dispatcher")) return true;
    if (std.mem.startsWith(u8, raw_type, "typedarray::") and std.mem.indexOf(u8, default_value, "[]") != null) {
        try writer.writeAll("Array.init(dispatcher)");
        return true;
    }
    const resolved = try resolver.resolveFor(raw_type, .argument, .builtin_file);
    if (resolved.kind == .@"enum") {
        if (resolved.is_bitfield) {
            try writer.writeAll("@as(");
            try writer.writeAll(resolved.zig);
            try writer.print(", @bitCast(@as(u{d}, ", .{resolved.bitfield_bits});
            try writer.writeAll(default_value);
            try writer.writeAll(")))");
        } else {
            try writer.writeAll("@as(");
            try writer.writeAll(resolved.zig);
            try writer.writeAll(", @fromBackingInt(@intCast(");
            try writer.writeAll(default_value);
            try writer.writeAll(")))");
        }
        return true;
    }
    if (std.mem.eql(u8, raw_type, "bool") or
        std.mem.eql(u8, raw_type, "int") or
        std.mem.eql(u8, raw_type, "float"))
    {
        try writer.writeAll(default_value);
        return true;
    }
    try writeBuiltinType(writer, resolver, raw_type, .argument);
    try writer.writeAll(".init(dispatcher)");
    return defaults.isEmptyConstructor(raw_type, default_value);
}

fn writeVarargMethod(
    writer: *Io.Writer,
    arena: Allocator,
    class: ExtensionApiJson.BuiltinClass,
    method: ExtensionApiJson.Method,
    real_name: []const u8,
    resolver: *const class_resolver.ClassResolver,
) !void {
    _ = real_name;
    const fixed_count = method.arguments.len;

    try docs.write(writer, arena, method.description, 0, "///");
    try writer.writeAll("pub fn ");
    try common.writeIdent(writer, .camel, method.name);
    try writer.writeAll("(");
    if (!method.is_static) {
        try writer.writeAll("self: ");
        try writer.writeAll(if (method.is_const) "*const " else "*");
        try writer.writeAll(class.name);
        try writer.writeAll(", dispatcher: anytype");
    } else {
        try writer.writeAll("dispatcher: anytype");
    }
    for (method.arguments) |argument| {
        try writer.writeAll(", ");
        try names.writeArgName(writer, argument.name, 0);
        try writer.writeAll(": ");
        try writeBuiltinType(writer, resolver, argument.type, .argument);
    }
    try writer.writeAll(", vargs: anytype) ");
    try writeBuiltinType(writer, resolver, method.return_type, .return_value);
    try writer.writeAll(" {\n");

    if (!method.is_static) {
        try writer.writeAll("    var self_variant = Variant.fromPtr(dispatcher, ");
        try writer.writeAll(class.name);
        try writer.writeAll(", ");
        try writer.writeAll("self");
        try writer.writeAll(");\n");
    }

    if (fixed_count != 0) {
        try writer.print("    var fixed: [{d}]Variant = undefined;\n", .{fixed_count});
        for (method.arguments, 0..) |argument, index| {
            try writer.print("    fixed[{d}] = Variant.fromPtr(dispatcher, @TypeOf(", .{index});
            try names.writeArgName(writer, argument.name, 0);
            try writer.writeAll("), &");
            try names.writeArgName(writer, argument.name, 0);
            try writer.writeAll(");\n");
        }
        try writer.print("    var args: [{d} + vargs.len]*Variant = undefined;\n", .{fixed_count});
        for (0..fixed_count) |index| {
            try writer.print("    args[{d}] = &fixed[{d}];\n", .{ index, index });
        }
    } else {
        try writer.writeAll("    var args: [vargs.len]*Variant = undefined;\n");
    }

    try writer.writeAll("    inline for (0..vargs.len) |i| {\n");
    try writer.writeAll("        if (@TypeOf(vargs[i]) != Variant) @compileError(\"vargs: should only contain 'Variant' types.\");\n");
    try writer.print("        args[{d} + i] = @constCast(&vargs[i]);\n", .{fixed_count});
    try writer.writeAll("    }\n");

    const returns_void = std.mem.eql(u8, method.return_type, "void") or std.mem.eql(u8, method.return_type, "Nil");
    if (!returns_void) {
        try writer.writeAll("    var result: Variant = Variant.nil();\n");
    }
    try writer.writeAll("    var err: interface.CallError = undefined;\n");
    try writer.writeAll("    var method_name = StringName.fromComptimeLatin1(dispatcher, \"");
    try names.writeEscaped(writer, method.name);
    try writer.writeAll("\");\n");
    try writer.writeAll("    dispatcher.dispatch(.variant_call, .{\n");
    if (method.is_static) {
        try writer.writeAll("        null,\n");
    } else {
        try writer.writeAll("        @ptrCast(&self_variant),\n");
    }
    try writer.writeAll("        @ptrCast(&method_name),\n");
    try writer.writeAll("        @ptrCast(&args),\n");
    try writer.writeAll("        @intCast(args.len),\n");
    if (returns_void) {
        try writer.writeAll("        null,\n");
    } else {
        try writer.writeAll("        @ptrCast(&result),\n");
    }
    try writer.writeAll("        &err,\n");
    try writer.writeAll("    });\n");

    if (!returns_void) {
        if (std.mem.eql(u8, method.return_type, "Variant")) {
            try writer.writeAll("    return result;\n");
        } else if (std.mem.eql(u8, method.return_type, "Callable")) {
            try writer.writeAll("    return result.asCallable();\n");
        } else {
            std.log.err("Unsupported vararg return type `{s}` for builtin {s}.{s}", .{ method.return_type, class.name, method.name });
            return error.UnsupportedVarargReturn;
        }
    }
    try writer.writeAll("}\n\n");
}

fn writeMethod(
    writer: *Io.Writer,
    arena: Allocator,
    api: ExtensionApiJson,
    class: ExtensionApiJson.BuiltinClass,
    method: ExtensionApiJson.Method,
    real_name: []const u8,
    resolver: *const class_resolver.ClassResolver,
) !void {
    _ = api;
    const method_pascal = try names.pascal(arena, method.name);

    var has_options = false;
    for (method.arguments) |argument| {
        if (argument.default_value != null) has_options = true;
    }
    if (has_options) {
        try writer.writeAll("pub const ");
        try writer.writeAll(method_pascal);
        try writer.writeAll("Options = struct {\n");
        for (method.arguments) |argument| {
            if (argument.default_value == null) continue;
            const default_value = argument.default_value.?;
            const inline_default = defaults.canInlineDefault(argument.type, default_value);
            try writer.writeAll("    ");
            try common.writeIdent(writer, .snake, argument.name);
            try writer.writeAll(": ");
            if (!inline_default) try writer.writeAll("?");
            try writeBuiltinType(writer, resolver, argument.type, .argument);
            if (inline_default) {
                try writer.writeAll(" = ");
                if (!try writeBuiltinDefault(writer, argument.type, default_value, real_name, resolver)) {
                    return error.UnsupportedInlineDefault;
                }
            } else {
                try writer.writeAll(" = null");
            }
            try writer.writeAll(",\n");
        }
        try writer.writeAll("};\n\n");
    }

    try docs.write(writer, arena, method.description, 0, "///");
    try writer.writeAll("pub fn ");
    try common.writeIdent(writer, .camel, method.name);
    try writer.writeAll("(");
    if (!method.is_static) {
        try writer.writeAll("self: ");
        try writer.writeAll(if (method.is_const) "*const " else "*");
        try writer.writeAll(class.name);
        try writer.writeAll(", dispatcher: anytype");
    } else {
        try writer.writeAll("dispatcher: anytype");
    }
    for (method.arguments, 0..) |argument, index| {
        if (argument.default_value != null) continue;
        try writer.writeAll(", ");
        try names.writeArgName(writer, argument.name, index);
        try writer.writeAll(": ");
        try writeBuiltinType(writer, resolver, argument.type, .argument);
    }
    if (has_options) {
        try writer.writeAll(", opt: ");
        try writer.writeAll(method_pascal);
        try writer.writeAll("Options");
    }
    try writer.writeAll(") ");
    try writeBuiltinType(writer, resolver, method.return_type, .return_value);
    try writer.writeAll(" {\n");

    for (method.arguments) |argument| {
        if (argument.default_value) |default_value| {
            if (defaults.canInlineDefault(argument.type, default_value)) continue;
            const needs_deinit = defaults.needsDeinit(argument.type, default_value);
            try writer.writeAll(if (needs_deinit) "    var " else "    const ");
            try names.writePrefixedIdent(writer, "actual_", argument.name);
            try writer.writeAll(" = opt.");
            try names.writeMemberIdent(writer, argument.name);
            try writer.writeAll(" orelse ");
            const parsed_default = try writeBuiltinDefault(writer, argument.type, default_value, real_name, resolver);
            try writer.writeAll(";\n");
            if (!parsed_default) {
                std.log.warn("Could not reconstruct default for {s}.{s}({s}): value `{s}` of type `{s}`", .{
                    class.name, method.name, argument.name, default_value, argument.type,
                });
            }
            if (needs_deinit) {
                try writer.writeAll("    defer ");
                try names.writePrefixedIdent(writer, "actual_", argument.name);
                try writer.writeAll(".deinit(dispatcher);\n");
            }
        }
    }

    try writer.print("    var args: [{d}]interface.ConstTypePtr = undefined;\n", .{method.arguments.len});
    for (method.arguments, 0..) |argument, index| {
        const has_default = argument.default_value != null;
        const inline_default = if (argument.default_value) |default_value|
            defaults.canInlineDefault(argument.type, default_value)
        else
            false;
        const resolved_argument = try resolver.resolveFor(argument.type, .argument, .builtin_file);
        if (resolved_argument.kind == .@"enum") {
            if (resolved_argument.is_bitfield) {
                try writer.print("    const arg{d}_slot: u{d} = @bitCast(", .{ index, resolved_argument.bitfield_bits });
            } else {
                try writer.print("    const arg{d}_slot: i64 = @backingInt(", .{index});
            }
            if (has_default) {
                if (inline_default) {
                    try writer.writeAll("opt.");
                    try names.writeMemberIdent(writer, argument.name);
                } else {
                    try names.writePrefixedIdent(writer, "actual_", argument.name);
                }
            } else {
                try names.writeArgName(writer, argument.name, index);
            }
            try writer.writeAll(");\n");
            try writer.print("    args[{d}] = @ptrCast(&arg{d}_slot);\n", .{ index, index });
        } else {
            try writer.print("    args[{d}] = @ptrCast(&", .{index});
            if (has_default) {
                if (inline_default) {
                    try writer.writeAll("opt.");
                    try names.writeMemberIdent(writer, argument.name);
                } else {
                    try names.writePrefixedIdent(writer, "actual_", argument.name);
                }
            } else {
                try names.writeArgName(writer, argument.name, index);
            }
            try writer.writeAll(");\n");
        }
    }

    const returns_void = std.mem.eql(u8, method.return_type, "void") or std.mem.eql(u8, method.return_type, "Nil");
    if (!returns_void) {
        try writer.writeAll("    var result: ");
        try writeBuiltinType(writer, resolver, method.return_type, .return_value);
        try writer.writeAll(" = ");
        try result_init.writeResultInitializer(writer, method.return_type, method.return_type, "dispatcher");
        try writer.writeAll(";\n");
    }

    const ptr_name = try names.pointer(arena, method.name);
    try writer.print("    if ({s}_ptr == null) {{\n", .{ptr_name});
    try writer.writeAll("        @branchHint(.cold);\n");
    if (std.mem.eql(u8, class.name, "StringName")) {
        try writer.writeAll("        var method_name = fromComptimeLatin1(dispatcher, \"");
    } else {
        try writer.writeAll("        var method_name = StringName.fromComptimeLatin1(dispatcher, \"");
    }
    try names.writeEscaped(writer, method.name);
    try writer.writeAll("\");\n");
    try writer.print("        {s}_ptr = dispatcher.dispatch(.variant_get_ptr_builtin_method, .{{\n", .{ptr_name});
    try writer.print("            interface.VariantType.{s},\n", .{try builtin_names.variantTypeName(arena, class.name)});
    try writer.writeAll("            @as(interface.ConstTypePtr, @ptrCast(&method_name)),\n");
    try writer.print("            {d},\n", .{method.hash});
    try writer.writeAll("        });\n");
    if (method.hash_compatibility.len != 0) {
        try writer.writeAll("        inline for ([_]u32{");
        for (method.hash_compatibility, 0..) |hash, index| {
            if (index != 0) try writer.writeAll(", ");
            try writer.print("{d}", .{hash});
        }
        try writer.writeAll("}) |compat_hash| {\n");
        try writer.print("            if ({s}_ptr == null) {s}_ptr = dispatcher.dispatch(.variant_get_ptr_builtin_method, .{{\n", .{ ptr_name, ptr_name });
        try writer.print("                interface.VariantType.{s},\n", .{try builtin_names.variantTypeName(arena, class.name)});
        try writer.writeAll("                @as(interface.ConstTypePtr, @ptrCast(&method_name)),\n");
        try writer.writeAll("                compat_hash,\n");
        try writer.writeAll("            });\n");
        try writer.writeAll("        }\n");
    }
    try writer.writeAll("        if (");
    try writer.print("{s}_ptr == null) @panic(\"", .{ptr_name});
    try writer.writeAll(class.name);
    try writer.writeAll(".");
    try writer.writeAll(method.name);
    try writer.writeAll(" was not found\");\n    }\n");

    try writer.print("    {s}_ptr.?(", .{ptr_name});
    if (method.is_static) {
        try writer.writeAll("null");
    } else {
        try writer.writeAll(if (method.is_const) "@as(interface.TypePtr, @ptrCast(@constCast(self)))" else "@as(interface.TypePtr, @ptrCast(self))");
    }
    try writer.writeAll(", @as([*c]const interface.ConstTypePtr, @ptrCast(&args)), ");
    if (returns_void) {
        try writer.writeAll("null");
    } else {
        try writer.writeAll("@as(interface.TypePtr, @ptrCast(&result))");
    }
    try writer.writeAll(", args.len);\n");
    if (!returns_void) try writer.writeAll("    return result;\n");
    try writer.writeAll("}\n");
    try writer.print("var {s}_ptr: interface.PtrBuiltInMethod = null;\n\n", .{ptr_name});
}

fn writeConstructor(
    writer: *Io.Writer,
    arena: Allocator,
    api: ExtensionApiJson,
    class: ExtensionApiJson.BuiltinClass,
    constructor: ExtensionApiJson.Constructor,
    real_name: []const u8,
    resolver: *const class_resolver.ClassResolver,
) !void {
    _ = api;
    _ = real_name;
    const name = try builtin_names.constructorName(arena, constructor);
    try docs.write(writer, arena, constructor.description, 0, "///");
    try writer.writeAll("pub fn ");
    try writer.writeAll(name);
    try writer.writeAll("(dispatcher: anytype");
    for (constructor.arguments, 0..) |argument, index| {
        try writer.writeAll(", ");
        try names.writeArgName(writer, argument.name, index);
        try writer.writeAll(": ");
        try writeBuiltinType(writer, resolver, argument.type, .argument);
    }
    try writer.print(") {s} {{\n", .{class.name});
    try writer.print("    var args: [{d}]interface.ConstTypePtr = undefined;\n", .{constructor.arguments.len});
    for (constructor.arguments, 0..) |argument, index| {
        try writer.print("    args[{d}] = @ptrCast(&", .{index});
        try names.writeArgName(writer, argument.name, index);
        try writer.writeAll(");\n");
    }
    try writer.print("    var result: {s} = undefined;\n", .{class.name});
    try writer.print("    if ({s}_ptr == null) {{\n", .{name});
    try writer.writeAll("        @branchHint(.cold);\n");
    try writer.print("        {s}_ptr = dispatcher.dispatch(.variant_get_ptr_constructor, .{{ interface.VariantType.{s}, {d} }}) orelse @panic(\"{s} constructor {s} was not found\");\n", .{ name, try builtin_names.variantTypeName(arena, class.name), constructor.index, class.name, name });
    try writer.writeAll("    }\n");
    try writer.print("    {s}_ptr.?(@as(interface.UninitializedTypePtr, @ptrCast(&result)), @as([*c]const interface.ConstTypePtr, @ptrCast(&args)));\n", .{name});
    try writer.writeAll("    return result;\n}\n");
    try writer.print("var {s}_ptr: interface.PtrConstructor = null;\n\n", .{name});
}

fn writeOperator(
    writer: *Io.Writer,
    arena: Allocator,
    api: ExtensionApiJson,
    class: ExtensionApiJson.BuiltinClass,
    operator: ExtensionApiJson.Operator,
    real_name: []const u8,
    resolver: *const class_resolver.ClassResolver,
) !void {
    _ = api;
    _ = real_name;
    const name = try builtin_names.operatorName(arena, operator);
    try docs.write(writer, arena, operator.description, 0, "///");
    try writer.writeAll("pub fn ");
    try writer.writeAll(name);
    try writer.writeAll("(self: *const ");
    try writer.writeAll(class.name);
    try writer.writeAll(", dispatcher: anytype");
    if (operator.right_type) |right_type| {
        try writer.writeAll(", rhs: *const ");
        try writeBuiltinType(writer, resolver, right_type, .argument);
    }
    try writer.writeAll(") ");
    try writeBuiltinType(writer, resolver, operator.return_type, .return_value);
    try writer.writeAll(" {\n");
    try writer.writeAll("    var result: ");
    try writeBuiltinType(writer, resolver, operator.return_type, .return_value);
    try writer.writeAll(" = ");
    try result_init.writeResultInitializer(writer, operator.return_type, operator.return_type, "dispatcher");
    try writer.writeAll(";\n");
    try writer.print("    if ({s}_ptr == null) {{\n", .{name});
    try writer.writeAll("        @branchHint(.cold);\n");
    try writer.print("        {s}_ptr = dispatcher.dispatch(.variant_get_ptr_operator_evaluator, .{{\n", .{name});
    try writer.print("            interface.VariantOperator.{s},\n", .{builtin_names.operatorTag(operator)});
    try writer.print("            interface.VariantType.{s},\n", .{try builtin_names.variantTypeName(arena, class.name)});
    if (operator.right_type) |right_type| {
        try writer.print("            interface.VariantType.{s},\n", .{try builtin_names.variantTypeName(arena, right_type)});
    } else {
        try writer.writeAll("            interface.VariantType.nil,\n");
    }
    try writer.writeAll("        }) orelse @panic(\"");
    try writer.writeAll(class.name);
    try writer.writeAll(" operator ");
    try writer.writeAll(name);
    try writer.writeAll(" was not found\");\n    }\n");
    try writer.print("    {s}_ptr.?(@as(interface.ConstTypePtr, @ptrCast(self)), ", .{name});
    if (operator.right_type != null) {
        try writer.writeAll("@as(interface.ConstTypePtr, @ptrCast(rhs))");
    } else {
        try writer.writeAll("null");
    }
    try writer.writeAll(", @as(interface.TypePtr, @ptrCast(&result)));\n");
    try writer.writeAll("    return result;\n}\n");
    try writer.print("var {s}_ptr: interface.PtrOperatorEvaluator = null;\n\n", .{name});
}

fn writeDestructor(writer: *Io.Writer, arena: Allocator, class: ExtensionApiJson.BuiltinClass) !void {
    try writer.writeAll("pub fn deinit(self: *");
    try writer.writeAll(class.name);
    try writer.writeAll(", dispatcher: anytype) void {\n");
    try writer.writeAll("    if (deinit_ptr == null) {\n");
    try writer.writeAll("        @branchHint(.cold);\n");
    try writer.print("        deinit_ptr = dispatcher.dispatch(.variant_get_ptr_destructor, .{{ interface.VariantType.{s} }}) orelse @panic(\"{s} destructor was not found\");\n", .{ try builtin_names.variantTypeName(arena, class.name), class.name });
    try writer.writeAll("    }\n");
    try writer.writeAll("    deinit_ptr.?(@as(interface.TypePtr, @ptrCast(self)));\n");
    try writer.writeAll("}\n");
    try writer.writeAll("var deinit_ptr: interface.PtrDestructor = null;\n\n");
}

const BuiltinTypeContext = enum {
    argument,
    return_value,
};

fn writeBuiltinType(
    writer: *Io.Writer,
    resolver: *const class_resolver.ClassResolver,
    raw: []const u8,
    context: BuiltinTypeContext,
) !void {
    const type_context: class_resolver.TypeContext = if (context == .return_value) .return_value else .argument;
    const resolved = try resolver.resolveFor(raw, type_context, .builtin_file);
    try writer.writeAll(resolved.zig);
}

const Usage = struct {
    classes: bool = false,
    enums: bool = false,
    native: bool = false,
};

fn classUsage(resolver: *const class_resolver.ClassResolver, class: ExtensionApiJson.BuiltinClass) !Usage {
    var usage = Usage{};
    for (class.methods) |method| {
        for (method.arguments) |argument| {
            try accountType(resolver, argument.type, &usage);
        }
        try accountType(resolver, method.return_type, &usage);
    }
    for (class.constructors) |constructor| {
        for (constructor.arguments) |argument| {
            try accountType(resolver, argument.type, &usage);
        }
    }
    for (class.operators) |operator| {
        try accountType(resolver, operator.return_type, &usage);
        if (operator.right_type) |right_type| try accountType(resolver, right_type, &usage);
    }
    return usage;
}

fn accountType(resolver: *const class_resolver.ClassResolver, raw: []const u8, usage: *Usage) !void {
    if (raw.len == 0) return;
    const resolved = try resolver.resolveFor(raw, .argument, .builtin_file);
    usage.classes = usage.classes or resolved.use_classes;
    usage.enums = usage.enums or resolved.import_enums;
    usage.native = usage.native or resolved.import_native;
}

fn writeImports(
    writer: *Io.Writer,
    arena: Allocator,
    api: ExtensionApiJson,
    class: ExtensionApiJson.BuiltinClass,
    catalog: *const builtin_catalog.BuiltinCatalog,
    resolver: *const class_resolver.ClassResolver,
) !void {
    try writer.writeAll("const std = @import(\"std\");\n");
    try writer.writeAll("const interface = @import(\"../interface.zig\");\n");
    const usage = try classUsage(resolver, class);
    if (usage.classes) try writer.writeAll("const classes = @import(\"../classes/classes.zig\");\n");
    if (usage.enums) try writer.writeAll("const enums = @import(\"../enums.zig\");\n");
    if (usage.native) try writer.writeAll("const native = @import(\"../native.zig\");\n");
    _ = api;
    for (catalog.entries) |entry| {
        if (std.mem.eql(u8, entry.name, class.name)) continue;
        const other_file = try names.snake(arena, entry.name);
        try writer.print("const {s} = @import(\"{s}.zig\").{s};\n", .{ entry.name, other_file, entry.name });
    }
}

fn findOffsets(offsets: []const ExtensionApiJson.ClassOffsets, name: []const u8) ?[]const ExtensionApiJson.MemberOffset {
    for (offsets) |entry| {
        if (std.mem.eql(u8, entry.name, name)) return entry.members;
    }
    return null;
}

fn findMember(class: ExtensionApiJson.BuiltinClass, name: []const u8) ?ExtensionApiJson.Member {
    for (class.members) |member| {
        if (std.mem.eql(u8, member.name, name)) return member;
    }
    return null;
}

