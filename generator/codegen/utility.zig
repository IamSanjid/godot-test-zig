//! Codegen utility-function wrappers, grouped by category.

pub fn generate(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const ClassResolver,
) !void {
    const utility_dir = try std.fs.path.join(arena, &.{ options.output_dir, "utility" });
    Io.Dir.cwd().createDirPath(io, utility_dir) catch |err| {
        std.log.err("Failed to create codegen utility directory `{s}`: {}", .{ utility_dir, err });
        return err;
    };

    var categories: [32][]const u8 = undefined;
    var category_count: usize = 0;
    for (api.utility_functions) |function| {
        var seen = false;
        for (categories[0..category_count]) |category| {
            if (std.mem.eql(u8, category, function.category)) {
                seen = true;
                break;
            }
        }
        if (seen) continue;
        categories[category_count] = function.category;
        category_count += 1;
    }
    std.mem.sort([]const u8, categories[0..category_count], {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.order(u8, a, b) == .lt;
        }
    }.lessThan);

    for (categories[0..category_count]) |category| {
        try writeCategory(arena, io, api, options, resolver, category);
    }
    try writeAggregator(arena, io, options, categories[0..category_count]);
}

fn writeCategory(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const ClassResolver,
    category: []const u8,
) !void {
    const file_name = try names.snake(arena, category);
    const relative_path = try std.fmt.allocPrint(arena, "utility/{s}.zig", .{file_name});
    const custom = (try custom_code.read(arena, io, relative_path)) orelse custom_code.Sections{};
    const full_path = try std.fs.path.join(arena, &.{ options.output_dir, relative_path });
    const file = Io.Dir.cwd().createFile(io, full_path, .{}) catch |err| {
        std.log.err("Failed to create codegen utility file `{s}`: {}", .{ full_path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush codegen utility file `{s}`: {}", .{ full_path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by codegen. Do not edit.\n\n");

    var emitted_names: [256][]const u8 = undefined;
    var emitted_count: usize = 0;
    var replacement_used: [64]bool = @splat(false);

    for (api.utility_functions) |function| {
        if (!std.mem.eql(u8, function.category, category)) continue;
        const generated_name = try names.camel(arena, function.name);
        if (custom.replacementIndex(generated_name)) |index| {
            replacement_used[index] = true;
            try custom_code.writeRaw(writer, custom.replacements[index].code);
            try writer.writeAll("\n");
        } else {
            try writeFunction(writer, arena, resolver, function);
        }
        emitted_names[emitted_count] = generated_name;
        emitted_count += 1;
    }

    for (custom.methods) |section| {
        if (hasName(emitted_names[0..emitted_count], section.name)) return error.DuplicateCustomMethod;
        try custom_code.writeRaw(writer, section.code);
        try writer.writeAll("\n");
    }

    for (custom.replacements, 0..) |section, index| {
        if (!replacement_used[index]) {
            std.log.err("Unknown custom utility replacement `{s}` in {s}", .{ section.name, relative_path });
            return error.UnknownCustomReplace;
        }
    }

    try writer.print("const bindings = @import(\"{s}\");\n", .{options.bindings_module});
    try writer.writeAll("const runtime = @import(\"../godot.zig\");\n");
    try writer.writeAll("const builtins = @import(\"../builtins/builtins.zig\");\n");
    try writer.writeAll("const classes = @import(\"../classes/classes.zig\");\n");
    try writer.writeAll("const enums = @import(\"../enums.zig\");\n");
    try writer.writeAll("const native = @import(\"../native.zig\");\n");
    try writer.writeAll("const std = @import(\"std\");\n");
    try custom_code.writeRaw(writer, custom.imports);
}

fn writeAggregator(
    arena: Allocator,
    io: Io,
    options: Options,
    categories: []const []const u8,
) !void {
    const path = try std.fs.path.join(arena, &.{ options.output_dir, "utility", "utility.zig" });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create codegen utility aggregator `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush codegen utility aggregator `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by codegen. Do not edit.\n\n");
    for (categories) |category| {
        const file_name = try names.snake(arena, category);
        try writer.writeAll("pub const ");
        try names.writeIdent(writer, .snake, category);
        try writer.print(" = @import(\"{s}.zig\");\n", .{file_name});
    }
}

fn writeFunction(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    function: ExtensionApiJson.UtilityFunction,
) !void {
    try docs.write(writer, arena, function.description, 0, "///");
    try writer.writeAll("pub inline fn ");
    try names.writeIdent(writer, .camel, function.name);
    try writer.writeAll("(");
    for (function.arguments, 0..) |argument, index| {
        if (index != 0) try writer.writeAll(", ");
        try names.writeArgName(writer, argument.name, index);
        try writer.writeAll(": ");
        const resolved = try type_mapping.resolveUtility(resolver, argument.type, .argument);
        try writer.writeAll(resolved.zig);
    }
    if (function.is_vararg) {
        if (function.arguments.len != 0) try writer.writeAll(", ");
        try writer.writeAll("vargs: anytype");
    }
    try writer.writeAll(") ");

    const return_type = function.return_type orelse "void";
    const resolved_return = try type_mapping.resolveUtility(resolver, return_type, .return_value);
    try writer.writeAll(resolved_return.zig);
    try writer.writeAll(" {\n");

    if (function.is_vararg) {
        try writer.writeAll("    var args: [vargs.len]bindings.builtins.Variant = undefined;\n");
        try writer.writeAll("    inline for (vargs, 0..) |value, i| {\n");
        try writer.writeAll("        if (@TypeOf(value) != builtins.Variant) @compileError(\"vargs: should only contain 'Variant' types.\");\n");
        try writer.writeAll("        args[i] = value.toBinding();\n");
        try writer.writeAll("    }\n");
    }

    if (resolved_return.kind == .void) {
        try writer.writeAll("    ");
    } else {
        try writer.writeAll("    const result = ");
    }
    try writer.writeAll("bindings.utility.");
    try names.writeIdent(writer, .snake, function.category);
    try writer.writeAll(".");
    try names.writeIdent(writer, .camel, function.name);
    try writer.writeAll("(runtime.dispatcher()");
    for (function.arguments, 0..) |argument, index| {
        try writer.writeAll(", ");
        const resolved = try type_mapping.resolveUtility(resolver, argument.type, .argument);
        try type_mapping.writeArg(writer, resolved, try argName(arena, argument.name, index));
    }
    if (function.is_vararg) try writer.writeAll(", args");
    try writer.writeAll(");\n");

    if (resolved_return.kind != .void) {
        try writer.writeAll("    return ");
        try type_mapping.writeReturn(writer, resolved_return, "result");
        try writer.writeAll(";\n");
    }
    try writer.writeAll("}\n\n");
}

fn argName(arena: Allocator, name: []const u8, index: usize) ![]const u8 {
    var buf: [160]u8 = undefined;
    var fixed: Io.Writer = .fixed(&buf);
    try names.writeArgName(&fixed, name, index);
    return arena.dupe(u8, fixed.buffered());
}

fn hasName(list: []const []const u8, name: []const u8) bool {
    for (list) |existing| {
        if (std.mem.eql(u8, existing, name)) return true;
    }
    return false;
}

const std = @import("std");
const Allocator = std.mem.Allocator;
const Io = std.Io;

const custom_code = @import("custom.zig");
const docs = @import("../model/docs.zig");
const names = @import("../model/names.zig");
const ExtensionApiJson = @import("../model/ExtensionApiJson.zig");
const ClassResolver = @import("../model/resolver.zig").ClassResolver;
const type_mapping = @import("type_mapping.zig");
const Options = @import("Options.zig");

test "utility renderer compiles" {
    _ = &generate;
}
