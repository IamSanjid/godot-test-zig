fn writeOptions(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    info: *const Info,
    method: *const ExtensionApiJson.ClassMethod,
    method_pascal: []const u8,
    imports: *ImportSet,
) !void {
    try writer.writeAll("    pub const ");
    try writer.writeAll(method_pascal);
    try writer.writeAll("Options = struct {\n");
    for (method.arguments) |argument| {
        if (argument.default_value == null) continue;
        const default_value = argument.default_value.?;
        const inline_default = defaults.canInlineDefault(argument.type, default_value);
        try writer.writeAll("        ");
        try names.writeMemberIdent(writer, argument.name);
        try writer.writeAll(": ");
        if (!inline_default) try writer.writeAll("?");
        try writeCodegenType(writer, resolver, imports, argument.type, .argument);
        if (inline_default) {
            try writer.writeAll(" = ");
            if (!try type_mapping.writeDefaultValue(writer, resolver, argument.type, default_value, .class_file)) {
                return error.UnsupportedInlineDefault;
            }
        } else {
            try writer.writeAll(" = null");
        }
        try writer.writeAll(",\n");
    }
    try writer.writeAll("\n        pub inline fn toBinding(self: @This()) ");
    try type_mapping.writeBindingClassPath(writer, info.class);
    try writer.print(".{s}Options {{\n", .{method_pascal});
    try writer.writeAll("            return .{\n");
    for (method.arguments) |argument| {
        if (argument.default_value == null) continue;
        const default_value = argument.default_value.?;
        const inline_default = defaults.canInlineDefault(argument.type, default_value);
        try writer.writeAll("                .");
        try names.writeMemberIdent(writer, argument.name);
        try writer.writeAll(" = ");
        if (inline_default) {
            const resolved = try type_mapping.resolve(resolver, argument.type, .argument);
            try type_mapping.writeSelfOptionValue(writer, arena, resolved, argument.name);
            try writer.writeAll(",\n");
            try accountImports(imports, resolved);
        } else {
            try writer.writeAll("if (self.");
            try names.writeMemberIdent(writer, argument.name);
            try writer.writeAll(") |value| ");
            const resolved = try type_mapping.resolve(resolver, argument.type, .argument);
            try type_mapping.writeOptionValue(writer, resolved, "value");
            try writer.writeAll(" else null,\n");
            try accountImports(imports, resolved);
        }
    }
    try writer.writeAll("            };\n        }\n    };\n\n");
}

fn writeCodegenType(
    writer: *Io.Writer,
    resolver: *const ClassResolver,
    imports: *ImportSet,
    raw: []const u8,
    context: type_mapping.TypeContext,
) !void {
    const resolved = try type_mapping.resolve(resolver, raw, context);
    try writer.writeAll(resolved.zig);
    try accountImports(imports, resolved);
}

fn accountImports(imports: *ImportSet, resolved: type_mapping.ResolvedType) !void {
    if (resolved.import_class) |name| try imports.add(name);
    if (resolved.import_native) imports.native = true;
    if (resolved.import_enums) imports.enums = true;
}

fn writeImports(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    info: *const Info,
    imports: *const ImportSet,
    options: Options,
) !void {
    const prefix = try resolver.rootPrefix(arena, info);
    try writer.print("const bindings = @import(\"{s}\");\n", .{options.bindings_module});
    try writer.print("const runtime = @import(\"{s}godot.zig\");\n", .{prefix});
    try writer.print("const builtins = @import(\"{s}builtins/builtins.zig\");\n", .{prefix});
    if (imports.native) try writer.print("const native = @import(\"{s}native.zig\");\n", .{prefix});
    if (imports.enums) try writer.print("const enums = @import(\"{s}enums.zig\");\n", .{prefix});
    try writer.writeAll("const std = @import(\"std\");\n");

    const current_alias = resolver.zigClassName(info.class.name);
    if (!std.mem.eql(u8, current_alias, info.class.name)) {
        try writer.print("const {s} = {s};\n", .{ current_alias, info.class.name });
    }

    for (imports.names[0..imports.count]) |name| {
        if (std.mem.eql(u8, name, info.class.name)) continue;
        const other = resolver.get(name) orelse continue;
        const rel = try resolver.relativeClassImport(arena, info, other);
        try writer.print("const {s} = @import(\"{s}\").{s};\n", .{ resolver.zigClassName(name), rel, name });
    }
}

fn hasMethodName(list: []const []const u8, name: []const u8) bool {
    for (list) |existing| {
        if (std.mem.eql(u8, existing, name)) return true;
    }
    return false;
}

const ImportSet = struct {
    names: [512][]const u8 = undefined,
    count: usize = 0,
    native: bool = false,
    enums: bool = false,

    fn add(self: *ImportSet, name: []const u8) !void {
        for (self.names[0..self.count]) |existing| {
            if (std.mem.eql(u8, existing, name)) return;
        }
        if (self.count == self.names.len) return error.TooManyImports;
        self.names[self.count] = name;
        self.count += 1;
    }

    fn addEnum(self: *ImportSet) void {
        self.enums = true;
    }
};

