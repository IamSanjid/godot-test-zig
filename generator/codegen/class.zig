//! Codegen class emission.
//!
//! The generated class is a codegen-owned opaque type. Methods forward to the
//! raw binding class through `runtime.dispatcher()`, converting values at the
//! boundary with the shared type mapper.

pub fn generate(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const ClassResolver,
    templates: *const template_mod.Set,
) !void {
    const classes_dir = try std.fs.path.join(arena, &.{ options.output_dir, "classes" });
    Io.Dir.cwd().createDirPath(io, classes_dir) catch |err| {
        std.log.err("Failed to create codegen classes directory `{s}`: {}", .{ classes_dir, err });
        return err;
    };

    for (resolver.infos) |*info| {
        if (info.class.api_type) |api_type| {
            const dir = try std.fs.path.join(arena, &.{ classes_dir, api_type });
            Io.Dir.cwd().createDirPath(io, dir) catch |err| {
                std.log.err("Failed to create codegen class directory `{s}`: {}", .{ dir, err });
                return err;
            };
        }
        try emitClass(arena, io, api, options, resolver, info, templates);
    }

    var seen_api_types: [16][]const u8 = undefined;
    var api_type_count: usize = 0;
    for (resolver.infos) |*info| {
        const api_type = info.class.api_type orelse continue;
        var seen = false;
        for (seen_api_types[0..api_type_count]) |existing| {
            if (std.mem.eql(u8, existing, api_type)) {
                seen = true;
                break;
            }
        }
        if (seen) continue;
        seen_api_types[api_type_count] = api_type;
        api_type_count += 1;
        try writeApiAggregator(arena, io, options, resolver, api_type);
    }
    try writeRootAggregator(arena, io, options, resolver);
}

const AggregatorEntry = struct {
    file_name: []const u8,
    type_name: []const u8,
};

fn writeApiAggregator(
    arena: Allocator,
    io: Io,
    options: Options,
    resolver: *const ClassResolver,
    api_type: []const u8,
) !void {
    var entries: [4096]AggregatorEntry = undefined;
    var count: usize = 0;
    for (resolver.infos) |*info| {
        const class_api = info.class.api_type orelse continue;
        if (!std.mem.eql(u8, class_api, api_type)) continue;
        entries[count] = .{
            .file_name = try names.snake(arena, info.class.name),
            .type_name = info.class.name,
        };
        count += 1;
    }
    std.mem.sort(AggregatorEntry, entries[0..count], {}, struct {
        fn lessThan(_: void, a: AggregatorEntry, b: AggregatorEntry) bool {
            return std.mem.order(u8, a.file_name, b.file_name) == .lt;
        }
    }.lessThan);

    const dir = try std.fs.path.join(arena, &.{ options.output_dir, "classes", api_type });
    const path = try std.fs.path.join(arena, &.{ dir, try std.mem.concat(arena, u8, &.{ api_type, ".zig" }) });
    const file = try createFile(io, path);
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush codegen class aggregator `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by codegen. Do not edit.\n\n");
    for (entries[0..count]) |entry| {
        try writer.print("pub const {s} = @import(\"{s}.zig\");\n", .{ entry.file_name, entry.file_name });
        try writer.print("pub const {s} = {s}.{s};\n", .{ entry.type_name, entry.file_name, entry.type_name });
    }
}

fn writeRootAggregator(
    arena: Allocator,
    io: Io,
    options: Options,
    resolver: *const ClassResolver,
) !void {
    var api_types: [16][]const u8 = undefined;
    var api_count: usize = 0;
    var outside: [256]AggregatorEntry = undefined;
    var outside_count: usize = 0;

    for (resolver.infos) |*info| {
        if (info.class.api_type) |api_type| {
            var seen = false;
            for (api_types[0..api_count]) |existing| {
                if (std.mem.eql(u8, existing, api_type)) {
                    seen = true;
                    break;
                }
            }
            if (!seen) {
                api_types[api_count] = api_type;
                api_count += 1;
            }
        } else {
            outside[outside_count] = .{
                .file_name = try names.snake(arena, info.class.name),
                .type_name = info.class.name,
            };
            outside_count += 1;
        }
    }
    std.mem.sort([]const u8, api_types[0..api_count], {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.order(u8, a, b) == .lt;
        }
    }.lessThan);
    std.mem.sort(AggregatorEntry, outside[0..outside_count], {}, struct {
        fn lessThan(_: void, a: AggregatorEntry, b: AggregatorEntry) bool {
            return std.mem.order(u8, a.file_name, b.file_name) == .lt;
        }
    }.lessThan);

    const path = try std.fs.path.join(arena, &.{ options.output_dir, "classes", "classes.zig" });
    const file = try createFile(io, path);
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush codegen classes aggregator `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by codegen. Do not edit.\n\n");
    for (api_types[0..api_count]) |api_type| {
        try writer.writeAll("pub const ");
        try names.writeFile(writer, api_type);
        try writer.print(" = @import(\"{s}/{s}.zig\");\n", .{ api_type, api_type });
    }
    for (outside[0..outside_count]) |entry| {
        try writer.print("pub const {s} = @import(\"{s}.zig\");\n", .{ entry.file_name, entry.file_name });
        try writer.print("pub const {s} = {s}.{s};\n", .{ entry.type_name, entry.file_name, entry.type_name });
    }
}

fn createFile(io: Io, path: []const u8) !Io.File {
    return Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create codegen file `{s}`: {}", .{ path, err });
        return err;
    };
}

fn emitClass(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const ClassResolver,
    info: *const Info,
    templates: *const template_mod.Set,
) !void {
    const class = info.class;
    const ancestry = try buildAncestry(arena, resolver, info);
    const active_templates = try templates.*.filtered(arena, .class, class.name, ancestry);
    const singleton = isSingleton(api, class.name);
    const custom_relative = try resolver.path(arena, info);
    const custom = (try custom_code.read(arena, io, custom_relative)) orelse custom_code.Sections{};
    const binding_class_path = try type_mapping.bindingClassPath(arena, class);
    const path = try resolver.path(arena, info);
    const full_path = try std.fs.path.join(arena, &.{ options.output_dir, path });
    const file = try createFile(io, full_path);
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush codegen class file `{s}`: {}", .{ full_path, err });
    };
    const writer = &streaming.interface;

    var imports: ImportSet = .{};
    const class_name = class.name;
    try writer.writeAll("// Generated by codegen. Do not edit.\n\n");
    try docs.write(writer, arena, class.brief_description, 0, "//!");
    try docs.write(writer, arena, class.description, 0, "//!");
    try writer.writeAll("\n");

    try writer.writeAll("pub const ");
    try names.writeRawIdent(writer, class_name);
    try writer.writeAll(" = opaque {\n");
    try names.writeGodotClassName(writer, class.name);
    try writer.writeAll("\n");

    if (resolver.baseInfo(info)) |base| {
        try writer.writeAll("    pub const Extends = ");
        try names.writeRawIdent(writer, resolver.zigClassName(base.class.name));
        try writer.writeAll(";\n\n");
        try imports.add(base.class.name);
    } else {
        try writer.writeAll("    pub const Extends = void;\n\n");
    }

    try writeClassConstants(writer, arena, resolver, info);
    try writeClassEnums(writer, arena, resolver, info);

    if (class.is_instantiable and !singleton) {
        try writeConstruct(writer, class, resolver);
    }

    try writeVirtuals(writer, arena, resolver, info, &imports);
    try writeSignals(writer, arena, resolver, info, &imports);
    try writeProperties(writer, arena, resolver, info, &imports);

    var emitted_names: [4096][]const u8 = undefined;
    var emitted_count: usize = 0;
    var emitted_code_names: [4096][]const u8 = undefined;
    var emitted_code_count: usize = 0;
    var emitted_static: [4096]bool = undefined;
    var replacement_used: [64]bool = @splat(false);

    for (class.methods) |*method| {
        if (method.is_virtual) {
            if (!method.is_required) {
                try writeVirtualWrapper(
                    writer,
                    arena,
                    resolver,
                    info,
                    method,
                    false,
                    &imports,
                    &custom,
                    &active_templates,
                    &replacement_used,
                    binding_class_path,
                );
                const code_name = resolver.virtualName(info, method.name);
                emitted_names[emitted_count] = method.name;
                emitted_count += 1;
                emitted_code_names[emitted_code_count] = code_name;
                emitted_static[emitted_code_count] = method.is_static;
                emitted_code_count += 1;
            }
            continue;
        }
        const code_name = try names.camel(arena, method.name);
        if (method.is_vararg) {
            try writeVarargMethod(
                writer,
                arena,
                resolver,
                info,
                info,
                method,
                null,
                &imports,
                &custom,
                &active_templates,
                &replacement_used,
                binding_class_path,
            );
        } else {
            try writeMethod(
                writer,
                arena,
                resolver,
                info,
                info,
                method,
                null,
                &imports,
                &custom,
                &active_templates,
                &replacement_used,
                binding_class_path,
            );
        }
        emitted_names[emitted_count] = method.name;
        emitted_count += 1;
        emitted_code_names[emitted_code_count] = code_name;
        emitted_static[emitted_code_count] = method.is_static;
        emitted_code_count += 1;
    }

    var base_info = resolver.baseInfo(info);
    while (base_info) |base| {
        try imports.add(base.class.name);
        for (base.class.methods) |*method| {
            if (hasMethodName(emitted_names[0..emitted_count], method.name)) continue;
            if (method.is_virtual) {
                if (method.is_required) continue;
                try writeVirtualWrapper(
                    writer,
                    arena,
                    resolver,
                    info,
                    method,
                    true,
                    &imports,
                    &custom,
                    &active_templates,
                    &replacement_used,
                    binding_class_path,
                );
                const code_name = resolver.virtualName(info, method.name);
                emitted_names[emitted_count] = method.name;
                emitted_count += 1;
                emitted_code_names[emitted_code_count] = code_name;
                emitted_static[emitted_code_count] = method.is_static;
                emitted_code_count += 1;
                continue;
            }
            const code_name = try names.camel(arena, method.name);
            if (method.is_vararg) {
                try writeVarargMethod(
                    writer,
                    arena,
                    resolver,
                    info,
                    base,
                    method,
                    null,
                    &imports,
                    &custom,
                    &active_templates,
                    &replacement_used,
                    binding_class_path,
                );
            } else {
                try writeMethod(
                    writer,
                    arena,
                    resolver,
                    info,
                    base,
                    method,
                    null,
                    &imports,
                    &custom,
                    &active_templates,
                    &replacement_used,
                    binding_class_path,
                );
            }
            emitted_names[emitted_count] = method.name;
            emitted_count += 1;
            emitted_code_names[emitted_code_count] = code_name;
            emitted_static[emitted_code_count] = method.is_static;
            emitted_code_count += 1;
        }
        base_info = resolver.baseInfo(base);
    }

    for (active_templates.list(.class)) |template| {
        if (template.kind != .method) continue;
        if (hasMethodName(emitted_code_names[0..emitted_code_count], template.method)) {
            std.log.err("Duplicate template class method `{s}` in {s}", .{ template.method, class.name });
            return error.DuplicateTemplateMethod;
        }
        const rendered = try template_mod.render(arena, template, .{
            .artifact = .class,
            .method = template.method,
            .class_name = class.name,
            .binding_class = binding_class_path,
            .api_type = class.api_type,
        });
        try custom_code.writeIndented(writer, rendered, 4);
        emitted_code_names[emitted_code_count] = template.method;
        emitted_code_count += 1;
    }

    for (custom.methods) |section| {
        if (hasMethodName(emitted_code_names[0..emitted_code_count], section.name)) {
            std.log.err("Duplicate custom class method `{s}` in {s}", .{ section.name, class.name });
            return error.DuplicateCustomMethod;
        }
        try custom_code.writeIndented(writer, section.code, 4);
    }
    for (custom.replacements, 0..) |section, index| {
        if (!replacement_used[index]) {
            std.log.err("Unknown custom class replacement `{s}` in {s}", .{ section.name, class.name });
            return error.UnknownCustomReplace;
        }
    }

    try function_metadata.write(
        writer,
        &emitted_code_names,
        &emitted_static,
        emitted_count,
        class_name,
        false,
        4,
    );

    try writer.writeAll("};\n\n");
    try writeImports(writer, arena, resolver, info, &imports, options);
    try custom_code.writeRaw(writer, custom.imports);
}

fn isSingleton(api: ExtensionApiJson, name: []const u8) bool {
    for (api.singletons) |singleton| {
        if (std.mem.eql(u8, singleton.type, name)) return true;
    }
    return false;
}

fn buildAncestry(
    arena: Allocator,
    resolver: *const ClassResolver,
    info: *const Info,
) ![]const []const u8 {
    var ancestor_names: std.ArrayList([]const u8) = .empty;
    var current: ?*const Info = info;
    while (current) |entry| {
        try ancestor_names.append(arena, entry.class.name);
        current = resolver.baseInfo(entry);
    }
    return ancestor_names.items;
}

fn writeConstruct(writer: *Io.Writer, class: *const ExtensionApiJson.Class, resolver: *const ClassResolver) !void {
    try writer.writeAll("    pub inline fn construct() ?*");
    try names.writeRawIdent(writer, class.name);
    try writer.writeAll(" {\n        const value = ");
    try type_mapping.writeBindingClassPath(writer, class);
    try writer.writeAll(".construct(runtime.dispatcher());\n");
    try writer.writeAll("        return if (value) |ptr| @ptrCast(ptr) else null;\n    }\n\n");
    _ = resolver;
}

fn writeClassConstants(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    info: *const Info,
) !void {
    var seen: [512][]const u8 = undefined;
    var seen_count: usize = 0;
    var current: ?*const Info = info;
    while (current) |class_info| {
        for (class_info.class.constants) |constant| {
            if (hasMethodName(seen[0..seen_count], constant.name)) continue;
            seen[seen_count] = constant.name;
            seen_count += 1;
            try docs.write(writer, arena, constant.description, 4, "///");
            try writer.writeAll("    pub const ");
            try names.writeConstant(writer, constant.name);
            try writer.writeAll(" = ");
            try type_mapping.writeBindingClassPath(writer, info.class);
            try writer.writeAll(".");
            try names.writeConstant(writer, constant.name);
            try writer.writeAll(";\n");
        }
        current = resolver.baseInfo(class_info);
    }
    if (seen_count != 0) try writer.writeAll("\n");
}

fn writeClassEnums(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    info: *const Info,
) !void {
    var seen: [512][]const u8 = undefined;
    var seen_count: usize = 0;
    var current: ?*const Info = info;
    while (current) |class_info| {
        for (class_info.class.enums) |class_enum| {
            if (hasMethodName(seen[0..seen_count], class_enum.name)) continue;
            seen[seen_count] = class_enum.name;
            seen_count += 1;
            try writer.writeAll("    pub const ");
            try names.writeTypeName(writer, class_enum.name);
            try writer.writeAll(" = ");
            try type_mapping.writeBindingClassPath(writer, class_info.class);
            try writer.writeAll(".");
            try names.writeTypeName(writer, class_enum.name);
            try writer.writeAll(";\n");
        }
        current = resolver.baseInfo(class_info);
    }
    if (seen_count != 0) try writer.writeAll("\n");
    _ = arena;
}

fn writeVirtuals(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    info: *const Info,
    imports: *ImportSet,
) !void {
    var has_virtual = false;
    for (info.class.methods) |method| {
        if (method.is_virtual) has_virtual = true;
    }
    if (!has_virtual) return;

    try writer.writeAll("    pub const Virtual = struct {\n");
    try writeVirtualGroup(writer, arena, resolver, info, info, imports, true);
    try writeVirtualGroup(writer, arena, resolver, info, info, imports, false);
    try writer.writeAll("    };\n\n");
}

fn writeVirtualGroup(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    info: *const Info,
    owner: *const Info,
    imports: *ImportSet,
    required: bool,
) !void {
    const group_name = if (required) "Required" else "Optional";
    try writer.print("        pub const {s} = struct {{\n", .{group_name});
    for (owner.class.methods) |*method| {
        if (!method.is_virtual or method.is_required != required) continue;
        try docs.write(writer, arena, method.description, 12, "///");
        try writer.writeAll("            pub const ");
        try names.writeRawIdent(writer, resolver.virtualName(info, method.name));
        try writer.writeAll(" = *const fn (");
        var first = true;
        if (!method.is_static) {
            try writer.writeAll("self: *");
            if (method.is_const) try writer.writeAll("const ");
            try names.writeRawIdent(writer, info.class.name);
            first = false;
        }
        for (method.arguments) |argument| {
            if (!first) try writer.writeAll(", ");
            first = false;
            try names.writeArgName(writer, argument.name, 0);
            try writer.writeAll(": ");
            try writeCodegenType(writer, resolver, imports, argument.type, .argument);
        }
        try writer.writeAll(") callconv(.c) ");
        if (method.return_value) |return_value| {
            try writeCodegenType(writer, resolver, imports, return_value.type, .return_value);
        } else {
            try writer.writeAll("void");
        }
        try writer.writeAll(";\n");
    }
    try writer.writeAll("        };\n\n");
}

fn writeSignals(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    info: *const Info,
    imports: *ImportSet,
) !void {
    var seen: [2048][]const u8 = undefined;
    var seen_count: usize = 0;
    var current: ?*const Info = info;
    while (current) |class_info| {
        for (class_info.class.signals) |signal| {
            if (hasMethodName(seen[0..seen_count], signal.name)) continue;
            seen[seen_count] = signal.name;
            seen_count += 1;
            try writeSignal(writer, arena, info, signal, imports);
        }
        current = resolver.baseInfo(class_info);
    }
}

fn writeSignal(
    writer: *Io.Writer,
    arena: Allocator,
    info: *const Info,
    signal: ExtensionApiJson.ClassSignal,
    imports: *ImportSet,
) !void {
    try docs.write(writer, arena, signal.description, 4, "///");
    const signal_type = try names.pascal(arena, signal.name);
    try writer.writeAll("    pub const ");
    try names.writeRawIdent(writer, signal_type);
    try writer.writeAll(" = struct {\n        pub const signal_name = \"");
    try names.writeEscaped(writer, signal.name);
    try writer.writeAll("\";\n\n");

    const connect_options = if (std.mem.eql(u8, info.class.name, "Object"))
        "ConnectOptions"
    else blk: {
        try imports.add("Object");
        break :blk "Object.ConnectOptions";
    };

    try writer.writeAll("        pub inline fn connect(self: *");
    try names.writeRawIdent(writer, info.class.name);
    try writer.print(", callable: builtins.Callable, opt: {s}) enums.Error {{\n", .{connect_options});
    try writer.writeAll("            return ");
    try type_mapping.writeBindingClassPath(writer, info.class);
    try writer.writeAll(".connect(@ptrCast(self), runtime.dispatcher(), bindings.builtins.StringName.fromComptimeLatin1(runtime.dispatcher(), \"");
    try names.writeEscaped(writer, signal.name);
    try writer.writeAll("\"), callable.toBinding(), opt.toBinding());\n        }\n\n");

    try writer.writeAll("        pub inline fn disconnect(self: *");
    try names.writeRawIdent(writer, info.class.name);
    try writer.writeAll(", callable: builtins.Callable) void {\n            return ");
    try type_mapping.writeBindingClassPath(writer, info.class);
    try writer.writeAll(".disconnect(@ptrCast(self), runtime.dispatcher(), bindings.builtins.StringName.fromComptimeLatin1(runtime.dispatcher(), \"");
    try names.writeEscaped(writer, signal.name);
    try writer.writeAll("\"), callable.toBinding());\n        }\n\n");

    try writer.writeAll("        pub inline fn isConnected(self: *");
    try names.writeRawIdent(writer, info.class.name);
    try writer.writeAll(", callable: builtins.Callable) bool {\n            return ");
    try type_mapping.writeBindingClassPath(writer, info.class);
    try writer.writeAll(".isConnected(@ptrCast(self), runtime.dispatcher(), bindings.builtins.StringName.fromComptimeLatin1(runtime.dispatcher(), \"");
    try names.writeEscaped(writer, signal.name);
    try writer.writeAll("\"), callable.toBinding());\n        }\n");

    imports.addEnum();
    try writer.writeAll("    };\n\n");
}

fn writeProperties(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    info: *const Info,
    imports: *ImportSet,
) !void {
    var has_any = false;
    var current: ?*const Info = info;
    while (current) |class_info| {
        if (class_info.class.properties.len != 0) {
            has_any = true;
            break;
        }
        current = resolver.baseInfo(class_info);
    }
    if (!has_any) return;

    try writer.writeAll("    pub const Properties = struct {\n");
    var seen: [2048][]const u8 = undefined;
    var seen_count: usize = 0;
    current = info;
    while (current) |class_info| {
        for (class_info.class.properties) |property| {
            if (hasMethodName(seen[0..seen_count], property.name)) continue;
            seen[seen_count] = property.name;
            seen_count += 1;
            try docs.write(writer, arena, property.description, 8, "///");
            try writer.writeAll("        pub const ");
            try names.writeMemberIdent(writer, property.name);
            try writer.writeAll(" = struct {\n            pub const Type = ");
            if (std.mem.indexOfScalar(u8, property.type, ',') != null) {
                try writer.writeAll("builtins.Variant");
            } else {
                try writeCodegenType(writer, resolver, imports, property.type, .return_value);
            }
            try writer.writeAll(";\n");
            try writer.writeAll("            pub const getter: ?[]const u8 = ");
            try writeOptionalString(writer, property.getter);
            try writer.writeAll(";\n            pub const setter: ?[]const u8 = ");
            try writeOptionalString(writer, property.setter);
            try writer.writeAll(";\n            pub const index: ?i64 = ");
            if (property.index) |index| {
                try writer.print("{d}", .{index});
            } else {
                try writer.writeAll("null");
            }
            try writer.writeAll(";\n        };\n\n");
        }
        current = resolver.baseInfo(class_info);
    }
    try writer.writeAll("    };\n\n");
}

fn writeOptionalString(writer: *Io.Writer, value: ?[]const u8) !void {
    if (value) |string| {
        try writer.writeAll("\"");
        try names.writeEscaped(writer, string);
        try writer.writeAll("\"");
    } else {
        try writer.writeAll("null");
    }
}

fn writeMethod(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    info: *const Info,
    owner: *const Info,
    method: *const ExtensionApiJson.ClassMethod,
    override_name: ?[]const u8,
    imports: *ImportSet,
    custom_sections: *const custom_code.Sections,
    templates: *const template_mod.Set,
    replacement_used: *[64]bool,
    binding_class_path: []const u8,
) !void {
    const method_pascal = try names.pascal(arena, method.name);
    var has_options = false;
    for (method.arguments) |argument| {
        if (argument.default_value != null) has_options = true;
    }
    if (has_options and override_name == null and owner == info) {
        try writeOptions(writer, arena, resolver, info, method, method_pascal, imports);
    }

    const generated_name = if (override_name) |name| name else try names.camel(arena, method.name);
    if (try overrides.write(writer, arena, custom_sections, templates, replacement_used, generated_name, .{
        .artifact = .class,
        .method = method.name,
        .class_name = info.class.name,
        .binding_class = binding_class_path,
        .api_type = info.class.api_type,
    }, 4)) return;

    try docs.write(writer, arena, method.description, 4, "///");
    try writer.writeAll("    pub inline fn ");
    if (override_name) |name| {
        try names.writeRawIdent(writer, name);
    } else {
        try names.writeMethod(writer, method.name);
    }
    try writer.writeAll("(");
    var first_arg = true;
    if (!method.is_static) {
        try writer.writeAll("self: *");
        if (method.is_const) try writer.writeAll("const ");
        try names.writeRawIdent(writer, info.class.name);
        first_arg = false;
    }
    for (method.arguments) |argument| {
        if (argument.default_value != null) continue;
        if (!first_arg) try writer.writeAll(", ");
        first_arg = false;
        try names.writeArgName(writer, argument.name, 0);
        try writer.writeAll(": ");
        try writeCodegenType(writer, resolver, imports, argument.type, .argument);
    }
    if (has_options) {
        if (!first_arg) try writer.writeAll(", ");
        first_arg = false;
        try writer.writeAll("opt: ");
        if (owner != info) {
            try names.writeRawIdent(writer, resolver.zigClassName(owner.class.name));
            try writer.writeAll(".");
        }
        try writer.writeAll(method_pascal);
        try writer.writeAll("Options");
        if (owner != info) try imports.add(owner.class.name);
    }
    try writer.writeAll(") ");
    const return_type = if (method.return_value) |return_value| return_value.type else "void";
    const resolved_return = try type_mapping.resolve(resolver, return_type, .return_value);
    try writer.writeAll(resolved_return.zig);
    try accountImports(imports, resolved_return);
    try writer.writeAll(" {\n");

    if (resolved_return.kind == .void) {
        try writer.writeAll("        ");
    } else {
        try writer.writeAll("        const result = ");
    }
    try type_mapping.writeBindingClassPath(writer, info.class);
    try writer.writeAll(".");
    if (override_name) |name| {
        try names.writeRawIdent(writer, name);
    } else {
        try names.writeMethod(writer, method.name);
    }
    try writer.writeAll("(");
    var first = true;
    if (!method.is_static) {
        try writer.writeAll("@ptrCast(self)");
        first = false;
    }
    if (!first) try writer.writeAll(", ");
    try writer.writeAll("runtime.dispatcher()");
    first = false;
    for (method.arguments) |argument| {
        if (argument.default_value != null) continue;
        if (!first) try writer.writeAll(", ");
        first = false;
        const resolved = try type_mapping.resolve(resolver, argument.type, .argument);
        try type_mapping.writeArg(writer, resolved, try namesArg(arena, argument.name, 0));
        try accountImports(imports, resolved);
    }
    if (has_options) {
        if (!first) try writer.writeAll(", ");
        first = false;
        try writer.writeAll("opt.toBinding()");
    }
    try writer.writeAll(");\n");

    if (resolved_return.kind != .void) {
        try writer.writeAll("        return ");
        try type_mapping.writeReturn(writer, resolved_return, "result");
        try writer.writeAll(";\n");
    }
    try writer.writeAll("    }\n\n");
}

fn namesArg(arena: Allocator, name: []const u8, index: usize) ![]const u8 {
    _ = index;
    var buf: [160]u8 = undefined;
    var fixed: Io.Writer = .fixed(&buf);
    try names.writeArgName(&fixed, name, 0);
    return arena.dupe(u8, fixed.buffered());
}

