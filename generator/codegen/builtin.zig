fn argName(arena: Allocator, name: []const u8, index: usize) ![]const u8 {
    var buf: [160]u8 = undefined;
    var fixed: Io.Writer = .fixed(&buf);
    try names.writeArgName(&fixed, name, index);
    return arena.dupe(u8, fixed.buffered());
}

fn findSize(sizes: []const ExtensionApiJson.Size, name: []const u8) ?usize {
    for (sizes) |size| {
        if (std.mem.eql(u8, size.name, name)) return size.size;
    }
    return null;
}

fn findOffsets(offsets: []const ExtensionApiJson.ClassOffsets, name: []const u8) ?[]const ExtensionApiJson.MemberOffset {
    for (offsets) |entry| {
        if (std.mem.eql(u8, entry.name, name)) return entry.members;
    }
    return null;
}

fn findMember(class: *const ExtensionApiJson.BuiltinClass, name: []const u8) ?ExtensionApiJson.Member {
    for (class.members) |member| {
        if (std.mem.eql(u8, member.name, name)) return member;
    }
    return null;
}

