//! Generated builtin baseline.
//!
//! Every non-primitive entry in `builtin_classes` gets a file under
//! `<out_dir>/builtins/generated/`. Generated builtins are ABI-compatible with
//! the binding builtins and forward their behavior to the raw binding layer.

pub fn generate(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const ClassResolver,
    templates: *const template_mod.Set,
) !void {
    const generated_dir = try std.fs.path.join(arena, &.{ options.output_dir, "builtins", "generated" });
    Io.Dir.cwd().createDirPath(io, generated_dir) catch |err| {
        std.log.err("Failed to create generated builtins directory `{s}`: {}", .{ generated_dir, err });
        return err;
    };

    const sizes = api.sizesFor(options.api.builtin_build_conf);
    const offsets = api.offsetsFor(options.api.builtin_build_conf);
    for (resolver.builtin_classes) |*class| {
        if (types.isPrimitive(class.name)) continue;
        const size = if (sizes) |entries| findSize(entries, class.name) else null;
        const field_offsets = if (offsets) |entries| findOffsets(entries, class.name) else null;
        try emitBuiltin(arena, io, api, options, resolver, class, size, field_offsets, generated_dir, templates);
    }
}

fn emitBuiltin(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const ClassResolver,
    class: *const ExtensionApiJson.BuiltinClass,
    expected_size: ?usize,
    field_offsets: ?[]const ExtensionApiJson.MemberOffset,
    generated_dir: []const u8,
    templates: *const template_mod.Set,
) !void {
    const file_name = try std.mem.concat(arena, u8, &.{ try names.snake(arena, class.name), ".zig" });
    const active_templates = try templates.*.filtered(arena, .builtin, class.name, &.{});
    const custom_relative = try std.fmt.allocPrint(arena, "builtins/{s}", .{file_name});
    const custom_sections = (try custom_code.read(arena, io, custom_relative)) orelse custom_code.Sections{};
    const binding_builtin = try std.fmt.allocPrint(arena, "builtins.{s}", .{class.name});
    const path = try std.fs.path.join(arena, &.{ generated_dir, file_name });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create generated builtin `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush generated builtin `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    var imports: ImportSet = .{};
    try writer.writeAll("// Generated by codegen. Do not edit.\n\n");
    try docs.write(writer, arena, class.brief_description, 0, "//!");
    try docs.write(writer, arena, class.description, 0, "//!");
    if (class.brief_description != null or class.description != null) try writer.writeAll("\n");

    const real_name = types.realTypeName(options.api.builtin_build_conf);
    const top_level = isHandwritten(class.name);
    const self_type = if (top_level)
        try std.fmt.allocPrint(arena, "builtins.{s}", .{class.name})
    else
        class.name;
    if (!top_level) {
        try writeStruct(writer, arena, class, field_offsets, expected_size, real_name, &imports, resolver, options);
        try writer.writeAll("\n");
    }

    for (class.enums) |class_enum| {
        try writer.writeAll("\n    pub const ");
        try names.writeTypeName(writer, class_enum.name);
        try writer.writeAll(" = ");
        try type_mapping.writeBindingBuiltinPath(writer, class.name);
        try writer.writeAll(".");
        try names.writeTypeName(writer, class_enum.name);
        try writer.writeAll(";\n");
    }

    var emitted_code_names: [512][]const u8 = undefined;
    var emitted_code_count: usize = 0;
    var emitted_static: [512]bool = undefined;
    var replacement_used: [64]bool = @splat(false);

    for (class.methods) |method| {
        try writer.writeAll("\n");
        if (method.is_vararg) {
            try writeVarargMethod(
                writer,
                arena,
                resolver,
                class,
                method,
                &imports,
                options,
                &custom_sections,
                &active_templates,
                &replacement_used,
                binding_builtin,
                top_level,
                self_type,
            );
        } else {
            try writeMethod(
                writer,
                arena,
                resolver,
                class,
                method,
                &imports,
                options,
                &custom_sections,
                &active_templates,
                &replacement_used,
                binding_builtin,
                top_level,
                self_type,
            );
        }
        emitted_code_names[emitted_code_count] = try names.camel(arena, method.name);
        emitted_static[emitted_code_count] = method.is_static;
        emitted_code_count += 1;
    }
    const method_count = emitted_code_count;
    for (class.constructors) |constructor| {
        try writer.writeAll("\n");
        try writeConstructor(writer, arena, resolver, class, constructor, &imports, top_level, self_type);
    }
    for (class.operators) |operator| {
        try writer.writeAll("\n");
        try writeOperator(writer, arena, resolver, class, operator, &imports, top_level, self_type);
    }
    if (class.has_destructor) {
        try writer.writeAll("\n    pub inline fn deinit(self: *");
        try writer.writeAll(self_type);
        try writer.writeAll(") void {\n        ");
        try type_mapping.writeBindingBuiltinPath(writer, class.name);
        try writer.writeAll(".deinit(@ptrCast(self), runtime.dispatcher());\n    }\n");
    }

    for (active_templates.list(.builtin)) |template| {
        if (template.kind != .method) continue;
        if (hasName(emitted_code_names[0..emitted_code_count], template.method)) {
            std.log.err("Duplicate template builtin method `{s}` in {s}", .{ template.method, class.name });
            return error.DuplicateTemplateMethod;
        }
        const rendered = try template_mod.render(arena, template, .{
            .artifact = .builtin,
            .method = template.method,
            .builtin_name = self_type,
            .binding_builtin = binding_builtin,
        });
        try custom_code.writeIndented(writer, rendered, 4);
        emitted_code_names[emitted_code_count] = template.method;
        emitted_code_count += 1;
    }

    for (custom_sections.methods) |section| {
        if (hasName(emitted_code_names[0..emitted_code_count], section.name)) {
            std.log.err("Duplicate custom builtin method `{s}` in {s}", .{ section.name, class.name });
            return error.DuplicateCustomMethod;
        }
        try custom_code.writeIndented(writer, section.code, 4);
    }
    for (custom_sections.replacements, 0..) |section, index| {
        if (!replacement_used[index]) {
            std.log.err("Unknown custom builtin replacement `{s}` in {s}", .{ section.name, class.name });
            return error.UnknownCustomReplace;
        }
    }

    try function_metadata.write(
        writer,
        &emitted_code_names,
        &emitted_static,
        method_count,
        class.name,
        top_level,
        if (top_level) 0 else 4,
    );

    if (!top_level) {
        try writer.writeAll("};\n\n");
        if (expected_size) |size| {
            try writer.print("comptime {{\n    checkTypeLayout({s}, {d});\n}}\n\n", .{ class.name, size });
            try writeLayoutCheck(writer, class, field_offsets);
        }
    }
    try writeImports(writer, arena, class, &imports, options);
    try custom_code.writeRaw(writer, custom_sections.imports);
    _ = api;
}

fn writeStruct(
    writer: *Io.Writer,
    arena: Allocator,
    class: *const ExtensionApiJson.BuiltinClass,
    field_offsets: ?[]const ExtensionApiJson.MemberOffset,
    expected_size: ?usize,
    real_name: []const u8,
    imports: *ImportSet,
    resolver: *const ClassResolver,
    options: Options,
) !void {
    try writer.writeAll("pub const ");
    try names.writeRawIdent(writer, class.name);
    try writer.writeAll(" = extern struct {\n");
    try names.writeGodotClassName(writer, class.name);

    if (field_offsets) |members| {
        for (members) |member| {
            if (findMember(class, member.member)) |member_info| {
                try docs.write(writer, arena, member_info.description, 4, "///");
            }
            try writer.writeAll("    ");
            try names.writeRawIdent(writer, member.member);
            try writer.writeAll(": ");
            try writeMetaType(writer, resolver, imports, member.meta, real_name, class.name);
            try writeMemberInitializer(writer, options.api.member_initialization, resolver, imports, member.meta, real_name, class.name);
            try writer.writeAll(",\n");
        }
    } else if (expected_size) |size| {
        const pointer_align = types.pointerAlign(options.api.builtin_build_conf);
        try writer.print("    _opaque: [{d}]u8 align({d}),\n", .{ size, pointer_align });
    } else {
        try writer.writeAll("    _opaque: [0]u8,\n");
    }
}

fn writeMemberInitializer(
    writer: *Io.Writer,
    initialization: api_options.MemberInitialization,
    resolver: *const ClassResolver,
    imports: *ImportSet,
    raw: []const u8,
    real_name: []const u8,
    self_name: []const u8,
) !void {
    switch (initialization) {
        .none => {},
        .undefined => try writer.writeAll(" = undefined"),
        .zero => {
            try writer.writeAll(" = std.mem.zeroes(");
            try writeMetaType(writer, resolver, imports, raw, real_name, self_name);
            try writer.writeAll(")");
        },
    }
}

fn writeMetaType(
    writer: *Io.Writer,
    resolver: *const ClassResolver,
    imports: *ImportSet,
    meta: []const u8,
    real_name: []const u8,
    self_name: []const u8,
) !void {
    if (std.mem.eql(u8, meta, "float")) return writer.writeAll(real_name);
    if (std.mem.eql(u8, meta, "int32")) return writer.writeAll("i32");
    if (std.mem.eql(u8, meta, "int64")) return writer.writeAll("i64");
    if (std.mem.eql(u8, meta, "bool")) return writer.writeAll("bool");
    return writeType(writer, resolver, imports, meta, .argument, self_name, false);
}

fn writeMethod(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    class: *const ExtensionApiJson.BuiltinClass,
    method: ExtensionApiJson.Method,
    imports: *ImportSet,
    options: Options,
    custom_sections: *const custom_code.Sections,
    templates: *const template_mod.Set,
    replacement_used: *[64]bool,
    binding_builtin: []const u8,
    top_level: bool,
    self_type: []const u8,
) !void {
    const method_pascal = try names.pascal(arena, method.name);
    var has_options = false;
    for (method.arguments) |argument| {
        if (argument.default_value != null) has_options = true;
    }
    if (has_options) {
        try writeOptions(writer, arena, resolver, class, method, method_pascal, imports, top_level);
    }

    const generated_name = try names.camel(arena, method.name);
    if (try overrides.write(writer, arena, custom_sections, templates, replacement_used, generated_name, .{
        .artifact = .builtin,
        .method = method.name,
        .builtin_name = self_type,
        .binding_builtin = binding_builtin,
    }, 4)) return;

    try docs.write(writer, arena, method.description, 4, "///");
    try writer.writeAll("    pub inline fn ");
    try names.writeMethod(writer, method.name);
    try writer.writeAll("(");
    var first = true;
    if (!method.is_static) {
        try writer.writeAll("self: ");
        try writer.writeAll(if (method.is_const) "*const " else "*");
        try writer.writeAll(self_type);
        first = false;
    }
    for (method.arguments) |argument| {
        if (argument.default_value != null) continue;
        if (!first) try writer.writeAll(", ");
        first = false;
        try names.writeArgName(writer, argument.name, 0);
        try writer.writeAll(": ");
        try writeType(writer, resolver, imports, argument.type, .argument, class.name, top_level);
    }
    if (has_options) {
        if (!first) try writer.writeAll(", ");
        first = false;
        try writer.writeAll("opt: ");
        try writer.writeAll(method_pascal);
        try writer.writeAll("Options");
    }
    try writer.writeAll(") ");
    const resolved_return = try resolver.resolveFor(method.return_type, .return_value, .utility_file);
    try writeResolvedType(writer, resolved_return, class.name, top_level);
    try accountImports(imports, resolved_return);
    try writer.writeAll(" {\n");

    if (resolved_return.kind == .void) {
        try writer.writeAll("        ");
    } else {
        try writer.writeAll("        const result = ");
    }
    try type_mapping.writeBindingBuiltinPath(writer, class.name);
    try writer.writeAll(".");
    try names.writeMethod(writer, method.name);
    try writer.writeAll("(");
    first = true;
    if (!method.is_static) {
        try writer.writeAll("@ptrCast(self)");
        first = false;
    }
    if (!first) try writer.writeAll(", ");
    try writer.writeAll("runtime.dispatcher()");
    first = false;
    for (method.arguments) |argument| {
        if (argument.default_value != null) continue;
        if (!first) try writer.writeAll(", ");
        first = false;
        const resolved = try resolver.resolveFor(argument.type, .argument, .utility_file);
        try type_mapping.writeArg(writer, resolved, try argName(arena, argument.name, 0));
        try accountImports(imports, resolved);
    }
    if (has_options) {
        if (!first) try writer.writeAll(", ");
        first = false;
        try writer.writeAll("opt.toBinding()");
    }
    try writer.writeAll(");\n");
    if (resolved_return.kind != .void) {
        try writer.writeAll("        return ");
        try writeReturn(writer, resolved_return, "result", class.name, top_level);
        try writer.writeAll(";\n");
    }
    try writer.writeAll("    }\n");
    _ = options;
}

fn writeVarargMethod(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    class: *const ExtensionApiJson.BuiltinClass,
    method: ExtensionApiJson.Method,
    imports: *ImportSet,
    options: Options,
    custom_sections: *const custom_code.Sections,
    templates: *const template_mod.Set,
    replacement_used: *[64]bool,
    binding_builtin: []const u8,
    top_level: bool,
    self_type: []const u8,
) !void {
    const generated_name = try names.camel(arena, method.name);
    if (try overrides.write(writer, arena, custom_sections, templates, replacement_used, generated_name, .{
        .artifact = .builtin,
        .method = method.name,
        .builtin_name = self_type,
        .binding_builtin = binding_builtin,
    }, 4)) return;

    try docs.write(writer, arena, method.description, 4, "///");
    try writer.writeAll("    pub inline fn ");
    try names.writeMethod(writer, method.name);
    try writer.writeAll("(");
    var first = true;
    if (!method.is_static) {
        try writer.writeAll("self: ");
        try writer.writeAll(if (method.is_const) "*const " else "*");
        try writer.writeAll(self_type);
        first = false;
    }
    for (method.arguments) |argument| {
        if (!first) try writer.writeAll(", ");
        first = false;
        try names.writeArgName(writer, argument.name, 0);
        try writer.writeAll(": ");
        try writeType(writer, resolver, imports, argument.type, .argument, class.name, top_level);
    }
    if (!first) try writer.writeAll(", ");
    try writer.writeAll("vargs: anytype) ");
    const resolved_return = try resolver.resolveFor(method.return_type, .return_value, .utility_file);
    try writeResolvedType(writer, resolved_return, class.name, top_level);
    try accountImports(imports, resolved_return);
    try writer.writeAll(" {\n");
    try writer.writeAll("        var args: [vargs.len]bindings.builtins.Variant = undefined;\n");
    try writer.writeAll("        inline for (vargs, 0..) |value, i| {\n");
    try writer.writeAll("            if (@TypeOf(value) != builtins.Variant) @compileError(\"vargs: should only contain 'Variant' types.\");\n");
    try writer.writeAll("            args[i] = value.toBinding();\n        }\n");

    if (resolved_return.kind == .void) {
        try writer.writeAll("        ");
    } else {
        try writer.writeAll("        const result = ");
    }
    try type_mapping.writeBindingBuiltinPath(writer, class.name);
    try writer.writeAll(".");
    try names.writeMethod(writer, method.name);
    try writer.writeAll("(");
    first = true;
    if (!method.is_static) {
        try writer.writeAll("@ptrCast(self)");
        first = false;
    }
    if (!first) try writer.writeAll(", ");
    try writer.writeAll("runtime.dispatcher()");
    first = false;
    for (method.arguments) |argument| {
        if (!first) try writer.writeAll(", ");
        first = false;
        const resolved = try resolver.resolveFor(argument.type, .argument, .utility_file);
        try type_mapping.writeArg(writer, resolved, try argName(arena, argument.name, 0));
        try accountImports(imports, resolved);
    }
    if (!first) try writer.writeAll(", ");
    try writer.writeAll("args);\n");
    if (resolved_return.kind != .void) {
        try writer.writeAll("        return ");
        try writeReturn(writer, resolved_return, "result", class.name, top_level);
        try writer.writeAll(";\n");
    }
    try writer.writeAll("    }\n");
    _ = options;
}

fn writeOptions(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    class: *const ExtensionApiJson.BuiltinClass,
    method: ExtensionApiJson.Method,
    method_pascal: []const u8,
    imports: *ImportSet,
    top_level: bool,
) !void {
    try writer.writeAll("    pub const ");
    try writer.writeAll(method_pascal);
    try writer.writeAll("Options = struct {\n");
    for (method.arguments) |argument| {
        if (argument.default_value == null) continue;
        const default_value = argument.default_value.?;
        const inline_default = defaults.canInlineDefault(argument.type, default_value);
        try writer.writeAll("        ");
        try names.writeMemberIdent(writer, argument.name);
        try writer.writeAll(": ");
        if (!inline_default) try writer.writeAll("?");
        try writeType(writer, resolver, imports, argument.type, .argument, class.name, top_level);
        if (inline_default) {
            try writer.writeAll(" = ");
            if (!try type_mapping.writeDefaultValue(writer, resolver, argument.type, default_value, .utility_file)) {
                return error.UnsupportedInlineDefault;
            }
        } else {
            try writer.writeAll(" = null");
        }
        try writer.writeAll(",\n");
    }
    try writer.writeAll("\n        pub inline fn toBinding(self: @This()) ");
    try type_mapping.writeBindingBuiltinPath(writer, class.name);
    try writer.print(".{s}Options {{\n", .{method_pascal});
    try writer.writeAll("            return .{\n");
    for (method.arguments) |argument| {
        if (argument.default_value == null) continue;
        const default_value = argument.default_value.?;
        const inline_default = defaults.canInlineDefault(argument.type, default_value);
        try writer.writeAll("                .");
        try names.writeMemberIdent(writer, argument.name);
        try writer.writeAll(" = ");
        if (inline_default) {
            const resolved = try resolver.resolveFor(argument.type, .argument, .utility_file);
            try type_mapping.writeSelfOptionValue(writer, arena, resolved, argument.name);
            try writer.writeAll(",\n");
            try accountImports(imports, resolved);
        } else {
            try writer.writeAll("if (self.");
            try names.writeMemberIdent(writer, argument.name);
            try writer.writeAll(") |value| ");
            const resolved = try resolver.resolveFor(argument.type, .argument, .utility_file);
            try type_mapping.writeOptionValue(writer, resolved, "value");
            try writer.writeAll(" else null,\n");
            try accountImports(imports, resolved);
        }
    }
    try writer.writeAll("            };\n        }\n    };\n\n");
}

fn writeConstructor(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    class: *const ExtensionApiJson.BuiltinClass,
    constructor: ExtensionApiJson.Constructor,
    imports: *ImportSet,
    top_level: bool,
    self_type: []const u8,
) !void {
    const name = try builtin_names.constructorName(arena, constructor);
    try docs.write(writer, arena, constructor.description, 4, "///");
    try writer.writeAll("    pub inline fn ");
    try names.writeRawIdent(writer, name);
    try writer.writeAll("(");
    var first = true;
    for (constructor.arguments) |argument| {
        if (!first) try writer.writeAll(", ");
        first = false;
        try names.writeArgName(writer, argument.name, 0);
        try writer.writeAll(": ");
        try writeType(writer, resolver, imports, argument.type, .argument, class.name, top_level);
    }
    try writer.writeAll(") ");
    try writer.writeAll(self_type);
    try writer.writeAll(" {\n        const value = ");
    try type_mapping.writeBindingBuiltinPath(writer, class.name);
    try writer.writeAll(".");
    try names.writeRawIdent(writer, name);
    try writer.writeAll("(runtime.dispatcher()");
    for (constructor.arguments) |argument| {
        try writer.writeAll(", ");
        const resolved = try resolver.resolveFor(argument.type, .argument, .utility_file);
        try type_mapping.writeArg(writer, resolved, try argName(arena, argument.name, 0));
        try accountImports(imports, resolved);
    }
    try writer.writeAll(");\n");
    try writer.writeAll("        return ");
    try writer.writeAll(self_type);
    try writer.writeAll(".fromBinding(value);\n    }\n");
}

fn writeOperator(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver,
    class: *const ExtensionApiJson.BuiltinClass,
    operator: ExtensionApiJson.Operator,
    imports: *ImportSet,
    top_level: bool,
    self_type: []const u8,
) !void {
    const name = try builtin_names.operatorName(arena, operator);
    try docs.write(writer, arena, operator.description, 4, "///");
    try writer.writeAll("    pub inline fn ");
    try names.writeRawIdent(writer, name);
    try writer.writeAll("(self: *const ");
    try writer.writeAll(self_type);
    if (operator.right_type) |right_type| {
        try writer.writeAll(", rhs: *const ");
        try writeType(writer, resolver, imports, right_type, .argument, class.name, top_level);
    }
    try writer.writeAll(") ");
    const resolved_return = try resolver.resolveFor(operator.return_type, .return_value, .utility_file);
    try writeResolvedType(writer, resolved_return, class.name, top_level);
    try accountImports(imports, resolved_return);
    try writer.writeAll(" {\n        const result = ");
    try type_mapping.writeBindingBuiltinPath(writer, class.name);
    try writer.writeAll(".");
    try names.writeRawIdent(writer, name);
    try writer.writeAll("(@ptrCast(self), runtime.dispatcher()");
    if (operator.right_type) |right_type| {
        const resolved = try resolver.resolveFor(right_type, .argument, .utility_file);
        switch (resolved.kind) {
            .builtin, .variant, .class_ptr => try writer.writeAll(", @ptrCast(rhs)"),
            else => try writer.writeAll(", rhs"),
        }
        try accountImports(imports, resolved);
    }
    try writer.writeAll(");\n        return ");
    try writeReturn(writer, resolved_return, "result", class.name, top_level);
    try writer.writeAll(";\n    }\n");
}

fn writeType(
    writer: *Io.Writer,
    resolver: *const ClassResolver,
    imports: *ImportSet,
    raw: []const u8,
    context: type_mapping.TypeContext,
    self_name: []const u8,
    top_level: bool,
) !void {
    const resolved = try resolver.resolveFor(raw, context, .utility_file);
    try writeResolvedType(writer, resolved, self_name, top_level);
    try accountImports(imports, resolved);
}

fn writeResolvedType(writer: *Io.Writer, resolved: type_mapping.ResolvedType, self_name: []const u8, top_level: bool) !void {
    if (top_level) {
        try writer.writeAll(resolved.zig);
        return;
    }
    if (std.mem.eql(u8, resolved.zig, "builtins.Variant")) {
        try writer.writeAll(resolved.zig);
        return;
    }
    const prefix = "builtins.";
    if (std.mem.startsWith(u8, resolved.zig, prefix)) {
        const rest = resolved.zig[prefix.len..];
        if (isSelfType(rest, self_name)) {
            try writer.writeAll(self_name);
            try writer.writeAll(rest[self_name.len..]);
            return;
        }
    }
    try writer.writeAll(resolved.zig);
}

fn isSelfType(name: []const u8, self_name: []const u8) bool {
    if (std.mem.eql(u8, name, self_name)) return true;
    return name.len > self_name.len and
        std.mem.startsWith(u8, name, self_name) and
        name[self_name.len] == '.';
}

fn writeReturn(writer: *Io.Writer, resolved: type_mapping.ResolvedType, expr: []const u8, self_name: []const u8, top_level: bool) !void {
    switch (resolved.kind) {
        .class_ptr => {
            if (std.mem.startsWith(u8, resolved.zig, "?*")) {
                try writer.print("if ({s}) |ptr| @ptrCast(ptr) else null", .{expr});
            } else {
                try writer.print("@ptrCast({s})", .{expr});
            }
        },
        .builtin => {
            if (!top_level and std.mem.startsWith(u8, resolved.zig, "builtins.") and
                std.mem.eql(u8, resolved.zig["builtins.".len..], self_name))
            {
                try writer.print("{s}.fromBinding({s})", .{ self_name, expr });
            } else {
                try writer.print("{s}.fromBinding({s})", .{ resolved.zig, expr });
            }
        },
        .variant => try writer.print("{s}.fromBinding({s})", .{ resolved.zig, expr }),
        .primitive, .native_ptr, .@"enum", .void => try writer.writeAll(expr),
    }
}

fn accountImports(imports: *ImportSet, resolved: type_mapping.ResolvedType) !void {
    if (resolved.import_class) |name| try imports.add(name);
    if (resolved.use_classes) imports.classes = true;
    if (resolved.import_enums) imports.enums = true;
    if (resolved.import_native) imports.native = true;
}

fn writeLayoutCheck(
    writer: *Io.Writer,
    class: *const ExtensionApiJson.BuiltinClass,
    field_offsets: ?[]const ExtensionApiJson.MemberOffset,
) !void {
    try writer.writeAll("fn checkTypeLayout(comptime T: type, comptime expected_size: usize) void {\n");
    try writer.print("    if (@sizeOf(T) != expected_size) @compileError(std.fmt.comptimePrint(\"{s}: expected size {{d}}, found {{d}}\", .{{ expected_size, @sizeOf(T) }}));\n", .{class.name});
    try writer.writeAll("    if (@alignOf(T) != @alignOf(");
    try writer.print("bindings.builtins.{s}", .{class.name});
    try writer.writeAll(")) @compileError(\"");
    try writer.writeAll(class.name);
    try writer.writeAll(": alignment mismatch\");\n");
    if (field_offsets) |members| {
        for (members) |member| {
            try writer.print("    if (@offsetOf(T, \"{s}\") != {d}) @compileError(std.fmt.comptimePrint(\"{s}.{s}: expected offset {d}, found {{d}}\", .{{@offsetOf(T, \"{s}\")}}));\n", .{ member.member, member.offset, class.name, member.member, member.offset, member.member });
        }
    }
    try writer.writeAll("}\n");
}

