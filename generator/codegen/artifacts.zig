//! Small codegen artifacts that are aliases plus singleton helpers.

pub fn generateGlobals(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
) !void {
    try writeConstants(arena, io, api, options);
    try writeEnums(arena, io, api, options);
}

pub fn generateNative(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
) !void {
    const path = try std.fs.path.join(arena, &.{ options.output_dir, "native.zig" });
    const file = try createFile(io, path);
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush codegen native file `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by codegen. Do not edit.\n\n");
    for (api.native_structures) |structure| {
        try writer.writeAll("pub const ");
        try names.writeRawIdent(writer, structure.name);
        try writer.writeAll(" = bindings.native.");
        try names.writeRawIdent(writer, structure.name);
        try writer.writeAll(";\n");
    }
    try writer.print("\nconst bindings = @import(\"{s}\");\n", .{options.bindings_module});
}

pub fn generateSingletons(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const ClassResolver,
) !void {
    const path = try std.fs.path.join(arena, &.{ options.output_dir, "singletons.zig" });
    const file = try createFile(io, path);
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush codegen singletons file `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by codegen. Do not edit.\n\n");
    for (api.singletons) |singleton| {
        const info = resolver.get(singleton.type) orelse {
            std.log.warn("Codegen singleton {s} has unknown type {s}", .{ singleton.name, singleton.type });
            continue;
        };
        const type_name = info.class.name;
        try writer.writeAll("pub const ");
        try names.writeRawIdent(writer, singleton.name);
        try writer.writeAll(" = struct {\n    var instance: ?*classes.");
        if (info.class.api_type) |api_type| {
            try names.writeIdent(writer, .snake, api_type);
            try writer.writeAll(".");
        }
        try names.writeRawIdent(writer, type_name);
        try writer.writeAll(" = null;\n\n");

        try writer.writeAll("    pub inline fn get() *classes.");
        if (info.class.api_type) |api_type| {
            try names.writeIdent(writer, .snake, api_type);
            try writer.writeAll(".");
        }
        try names.writeRawIdent(writer, type_name);
        try writer.writeAll(" {\n        if (instance == null) {\n            @branchHint(.cold);\n");
        try writer.writeAll("            const value = bindings.singletons.Singleton(");
        try type_mapping.writeBindingClassPath(writer, info.class);
        try writer.writeAll(", \"");
        try names.writeEscaped(writer, singleton.name);
        try writer.writeAll("\").get(runtime.dispatcher());\n");
        try writer.writeAll("            instance = @ptrCast(value);\n        }\n        return instance.?;\n    }\n};\n\n");
    }

    try writer.print("const bindings = @import(\"{s}\");\n", .{options.bindings_module});
    try writer.writeAll("const runtime = @import(\"godot.zig\");\n");
    try writer.writeAll("const classes = @import(\"classes/classes.zig\");\n");
}

fn writeConstants(arena: Allocator, io: Io, api: ExtensionApiJson, options: Options) !void {
    const path = try std.fs.path.join(arena, &.{ options.output_dir, "constants.zig" });
    const file = try createFile(io, path);
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush codegen constants file `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by codegen. Do not edit.\n\n");
    for (api.global_constants) |constant| {
        try docs.write(writer, arena, constant.description, 0, "///");
        try writer.writeAll("pub const ");
        try names.writeIdent(writer, .snake, constant.name);
        try writer.print(" = {d};\n", .{constant.value});
    }
}

fn writeEnums(arena: Allocator, io: Io, api: ExtensionApiJson, options: Options) !void {
    const path = try std.fs.path.join(arena, &.{ options.output_dir, "enums.zig" });
    const file = try createFile(io, path);
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush codegen enums file `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by codegen. Do not edit.\n\n");
    for (api.global_enums) |global_enum| {
        try writer.writeAll("pub const ");
        try names.writeIdent(writer, .pascal, global_enum.name);
        try writer.writeAll(" = bindings.enums.");
        try names.writeIdent(writer, .pascal, global_enum.name);
        try writer.writeAll(";\n");
    }
    try writer.print("\nconst bindings = @import(\"{s}\");\n", .{options.bindings_module});
}

fn createFile(io: Io, path: []const u8) !Io.File {
    return Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create codegen file `{s}`: {}", .{ path, err });
        return err;
    };
}

const std = @import("std");
const Allocator = std.mem.Allocator;
const Io = std.Io;

const names = @import("../model/names.zig");
const docs = @import("../model/docs.zig");
const ExtensionApiJson = @import("../model/ExtensionApiJson.zig");
const ClassResolver = @import("../model/resolver.zig").ClassResolver;
const type_mapping = @import("type_mapping.zig");
const Options = @import("Options.zig");

test "codegen artifact renderers compile" {
    _ = &generateGlobals;
    _ = &generateNative;
    _ = &generateSingletons;
}
