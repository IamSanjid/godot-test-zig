//! Orchestrates wrapper generation.
//!
//! The file is written in three passes:
//! 1. enums, handles and aliases, in interface-JSON order,
//! 2. structs and function typedefs, in interface-JSON order,
//! 3. the `ProcsTag`/`ProcsTypes` interface declarations.
//!
//! Structs/functions are emitted last because they are the bulk of the file and
//! reading the low-level typedefs first makes the generated wrapper easier to
//! navigate. Declaration order does not matter in Zig containers.
//!
//! All type-name analysis happens once, up front (see `gen/Registry.zig`);
//! emitters never need to buffer partial output or retry declarations whose
//! dependencies have not been seen yet. That removed the previous first-pass
//! allocating writers and the pending-type list, which were the largest source
//! of transient allocations in this generator.

pub fn generateInterfaceBindings(context: *Context, options: Options) !void {
    const arena = context.arena;
    const io = context.io;

    var buffer: [4096]u8 = undefined;
    var writer_streaming = context.interface_wrapper.writerStreaming(io, &buffer);
    defer writer_streaming.flush() catch |err| {
        std.log.err("Failed to flush interface wrapper file: {}", .{err});
    };

    const writer = &writer_streaming.interface;
    const interface_json = &context.interface_json;

    try writeHeader(writer, interface_json);

    const registry = try Registry.init(arena, interface_json.types, options.strip_deprecation);

    for (interface_json.types) |t| {
        if (options.strip_deprecation and t.deprecated != null) continue;
        switch (t.data) {
            .@"enum" => {
                try enum_gen.emit(arena, writer, registry, t);
                try writer.writeAll("\n");
            },
            .handle => {
                try handle_gen.emit(writer, registry, t);
                try writer.writeAll("\n");
            },
            .alias => {
                try alias_gen.emit(writer, registry, t);
                try writer.writeAll("\n");
            },
            .@"struct", .function => {},
        }
    }

    for (interface_json.types) |t| {
        if (options.strip_deprecation and t.deprecated != null) continue;
        switch (t.data) {
            .@"struct" => {
                try structure_gen.emit(writer, registry, options.member_initialization, t);
                try writer.writeAll("\n");
            },
            .function => {
                try function_gen.emit(writer, registry, t);
                try writer.writeAll("\n");
            },
            .@"enum", .handle, .alias => {},
        }
    }

    try interface_gen.emit(writer, registry, interface_json.interface, options.strip_deprecation);
    try writer.writeAll("\n");

    try writer.print("const gdi = @import(\"{s}\");\n", .{options.interface_import});
}

fn writeHeader(writer: *Io.Writer, interface_json: *const InterfaceJson) !void {
    // Deliberately no timestamp: regenerating with the same inputs must produce
    // a byte-identical file, otherwise every build dirties the working tree.
    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    for (interface_json._copyright) |line| {
        try writer.print("// {s}\n", .{line});
    }
    try writer.writeAll("\n");
}

