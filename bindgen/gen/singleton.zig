//! Global singleton accessors.

pub fn generate(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const class_resolver.ClassResolver,
) !void {
    const path = try std.fs.path.join(arena, &.{ options.output_dir, "singletons.zig" });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create singletons file `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush singletons file `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    try writer.writeAll(
        \\pub fn Singleton(comptime T: type, comptime name: [:0]const u8) type {
        \\    return struct {
        \\        var instance: ?*T = null;
        \\
        \\        pub inline fn get(dispatcher: anytype) *T {
        \\            if (instance == null) {
        \\                @branchHint(.cold);
        \\                var singleton_name = StringName.fromComptimeLatin1(dispatcher, name);
        \\                const found: ?*T = @ptrCast(dispatcher.dispatch(.global_get_singleton, .{@ptrCast(&singleton_name)}));
        \\                instance = found orelse @panic("Couldn't find any singleton for: " ++ name);
        \\            }
        \\            return instance.?;
        \\        }
        \\    };
        \\}
        \\
        \\
    );

    for (api.singletons) |singleton| {
        const info = resolver.get(singleton.type) orelse {
            std.log.warn("Singleton {s} has unknown type {s}", .{ singleton.name, singleton.type });
            continue;
        };
        try writer.writeAll("pub const ");
        try names.writeRawIdent(writer, singleton.name);
        try writer.writeAll(" = Singleton(classes.");
        if (info.class.api_type) |api_type| {
            try common.writeIdent(writer, .snake, api_type);
            try writer.writeAll(".");
        }
        try names.writeRawIdent(writer, info.class.name);
        try writer.writeAll(", \"");
        try names.writeEscaped(writer, singleton.name);
        try writer.writeAll("\");\n");
    }

    const sections = (try custom_code.readForOutput(arena, io, "singletons.zig")) orelse custom_code.Sections{};
    try custom_code.writeRaw(writer, sections.namespace_code);

    try writer.writeAll("\nconst classes = @import(\"classes/classes.zig\");\n");
    try writer.writeAll("const StringName = @import(\"builtins/string_name.zig\").StringName;\n");
}

const std = @import("std");
const Allocator = std.mem.Allocator;
const Io = std.Io;

const common = @import("common.zig");
const custom_code = @import("custom.zig");
const names = @import("names.zig");
const class_resolver = @import("class_resolver.zig");
const ExtensionApiJson = @import("../ExtensionApiJson.zig");
const Options = @import("../Options.zig");
