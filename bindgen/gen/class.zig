//! Class binding emission for `extension_api.json`.
//!
//! One file per class under `classes/<api_type>/<snake>.zig` (or
//! `classes/<snake>.zig` when `api_type` is absent). Functions live inside an
//! `opaque` type namespace so they feel like C++ methods.

pub fn generate(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const class_resolver.ClassResolver,
) !void {
    const classes_dir = try std.fs.path.join(arena, &.{ options.output_dir, "classes" });
    Io.Dir.cwd().createDirPath(io, classes_dir) catch |err| {
        std.log.err("Failed to create classes directory `{s}`: {}", .{ classes_dir, err });
        return err;
    };

    for (resolver.infos) |*info| {
        if (info.class.api_type) |api_type| {
            const dir = try std.fs.path.join(arena, &.{ classes_dir, api_type });
            Io.Dir.cwd().createDirPath(io, dir) catch |err| {
                std.log.err("Failed to create class directory `{s}`: {}", .{ dir, err });
                return err;
            };
        }
        try emitClass(arena, io, api, options, resolver, info);
    }

    var seen_api_types: [16][]const u8 = undefined;
    var api_type_count: usize = 0;
    for (resolver.infos) |*info| {
        const api_type = info.class.api_type orelse continue;
        var seen = false;
        for (seen_api_types[0..api_type_count]) |existing| {
            if (std.mem.eql(u8, existing, api_type)) {
                seen = true;
                break;
            }
        }
        if (seen) continue;
        seen_api_types[api_type_count] = api_type;
        api_type_count += 1;
        try writeApiAggregator(arena, io, options, resolver, api_type);
    }
    try writeRootAggregator(arena, io, options, resolver);
}

const AggregatorEntry = struct {
    file_name: []const u8,
    type_name: []const u8,
};

fn writeApiAggregator(
    arena: Allocator,
    io: Io,
    options: Options,
    resolver: *const class_resolver.ClassResolver,
    api_type: []const u8,
) !void {
    var entries: [4096]AggregatorEntry = undefined;
    var count: usize = 0;
    for (resolver.infos) |*info| {
        const class_api = info.class.api_type orelse continue;
        if (!std.mem.eql(u8, class_api, api_type)) continue;
        entries[count] = .{
            .file_name = try names.snake(arena, info.class.name),
            .type_name = info.class.name,
        };
        count += 1;
    }
    std.mem.sort(AggregatorEntry, entries[0..count], {}, struct {
        fn lessThan(_: void, a: AggregatorEntry, b: AggregatorEntry) bool {
            return std.mem.order(u8, a.file_name, b.file_name) == .lt;
        }
    }.lessThan);

    const dir = try std.fs.path.join(arena, &.{ options.output_dir, "classes", api_type });
    const path = try std.fs.path.join(arena, &.{ dir, try std.mem.concat(arena, u8, &.{ api_type, ".zig" }) });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create class aggregator `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush class aggregator `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    for (entries[0..count]) |entry| {
        try writer.print("pub const {s} = @import(\"{s}.zig\");\n", .{ entry.file_name, entry.file_name });
        try writer.print("pub const {s} = {s}.{s};\n", .{ entry.type_name, entry.file_name, entry.type_name });
    }
    const relative_path = try std.fmt.allocPrint(arena, "classes/{s}/{s}.zig", .{ api_type, api_type });
    const sections = (try custom_code.readForOutput(arena, io, relative_path)) orelse custom_code.Sections{};
    try custom_code.writeRaw(writer, sections.namespace_code);
}

fn writeRootAggregator(
    arena: Allocator,
    io: Io,
    options: Options,
    resolver: *const class_resolver.ClassResolver,
) !void {
    var api_types: [16][]const u8 = undefined;
    var api_count: usize = 0;
    var outside: [256]AggregatorEntry = undefined;
    var outside_count: usize = 0;

    for (resolver.infos) |*info| {
        if (info.class.api_type) |api_type| {
            var seen = false;
            for (api_types[0..api_count]) |existing| {
                if (std.mem.eql(u8, existing, api_type)) {
                    seen = true;
                    break;
                }
            }
            if (!seen) {
                api_types[api_count] = api_type;
                api_count += 1;
            }
        } else {
            outside[outside_count] = .{
                .file_name = try names.snake(arena, info.class.name),
                .type_name = info.class.name,
            };
            outside_count += 1;
        }
    }
    std.mem.sort([]const u8, api_types[0..api_count], {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.order(u8, a, b) == .lt;
        }
    }.lessThan);
    std.mem.sort(AggregatorEntry, outside[0..outside_count], {}, struct {
        fn lessThan(_: void, a: AggregatorEntry, b: AggregatorEntry) bool {
            return std.mem.order(u8, a.file_name, b.file_name) == .lt;
        }
    }.lessThan);

    const path = try std.fs.path.join(arena, &.{ options.output_dir, "classes", "classes.zig" });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create classes aggregator `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush classes aggregator `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    for (api_types[0..api_count]) |api_type| {
        try writer.writeAll("pub const ");
        try common.writeIdent(writer, .snake, api_type);
        try writer.print(" = @import(\"{s}/{s}.zig\");\n", .{ api_type, api_type });
    }
    for (outside[0..outside_count]) |entry| {
        try writer.print("pub const {s} = @import(\"{s}.zig\");\n", .{ entry.file_name, entry.file_name });
        try writer.print("pub const {s} = {s}.{s};\n", .{ entry.type_name, entry.file_name, entry.type_name });
    }
    const sections = (try custom_code.readForOutput(arena, io, "classes/classes.zig")) orelse custom_code.Sections{};
    try custom_code.writeRaw(writer, sections.namespace_code);
}

fn customConflictsWithClass(class: *const ExtensionApiJson.Class, code: []const u8) bool {
    for (class.methods) |method| {
        if (customDeclaresFunction(code, method.name)) return true;
    }
    return false;
}

fn customDeclaresFunction(code: []const u8, name: []const u8) bool {
    var lines = std.mem.splitScalar(u8, code, '\n');
    while (lines.next()) |line| {
        const trimmed = std.mem.trim(u8, line, " \r");
        const rest = if (std.mem.startsWith(u8, trimmed, "pub inline fn "))
            trimmed["pub inline fn ".len..]
        else if (std.mem.startsWith(u8, trimmed, "pub fn "))
            trimmed["pub fn ".len..]
        else if (std.mem.startsWith(u8, trimmed, "inline fn "))
            trimmed["inline fn ".len..]
        else
            continue;
        const open = std.mem.indexOfScalar(u8, rest, '(') orelse continue;
        if (std.mem.eql(u8, std.mem.trim(u8, rest[0..open], " "), name)) return true;
    }
    return false;
}

fn loadClassCustom(
    arena: Allocator,
    io: Io,
    resolver: *const class_resolver.ClassResolver,
    info: *const class_resolver.Info,
) !custom_code.Sections {
    const relative_path = try resolver.path(arena, info);
    const own = (try custom_code.readForOutput(arena, io, relative_path)) orelse custom_code.Sections{};
    var structs: [256]custom_code.StructSection = undefined;
    var count: usize = 0;

    for (own.structs) |section| {
        structs[count] = section;
        count += 1;
    }

    var base_info = resolver.baseInfo(info);
    while (base_info) |base| {
        const base_path = try resolver.path(arena, base);
        const base_sections = (try custom_code.readForOutput(arena, io, base_path)) orelse custom_code.Sections{};
        for (base_sections.structs) |section| {
            if (!section.emit_child) continue;
            if (std.mem.eql(u8, section.type_name, base.class.name) and customConflictsWithClass(info.class, section.code)) {
                std.log.warn("Skipping inherited custom member for {s}: {s} already declares it", .{ info.class.name, section.type_name });
                continue;
            }
            if (count == structs.len) return error.TooManyCustomSections;
            structs[count] = .{
                .type_name = if (std.mem.eql(u8, section.type_name, base.class.name))
                    info.class.name
                else
                    section.type_name,
                .code = section.code,
            };
            count += 1;
        }
        base_info = resolver.baseInfo(base);
    }

    return .{
        .namespace_code = own.namespace_code,
        .structs = try arena.dupe(custom_code.StructSection, structs[0..count]),
    };
}

fn emitClass(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const class_resolver.ClassResolver,
    info: *const class_resolver.Info,
) !void {
    const class = info.class;
    const singleton = isSingleton(api, class.name);
    const sections = try loadClassCustom(arena, io, resolver, info);
    const path = try resolver.path(arena, info);
    const full_path = try std.fs.path.join(arena, &.{ options.output_dir, path });
    const file = Io.Dir.cwd().createFile(io, full_path, .{}) catch |err| {
        std.log.err("Failed to create class file `{s}`: {}", .{ full_path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush class file `{s}`: {}", .{ full_path, err });
    };
    const writer = &streaming.interface;

    var imports: ImportSet = .{};
    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    const class_name = class.name;
    const real_name = types.realTypeName(options.builtin_build_conf);
    try docs.write(writer, arena, class.brief_description, 0, "//!");
    try docs.write(writer, arena, class.description, 0, "//!");
    try writer.writeAll("\n");

    try writer.writeAll("pub const ");
    try names.writeRawIdent(writer, class_name);
    try writer.writeAll(" = opaque {\n");

    if (class.inherits) |base_name| {
        try writer.writeAll("    pub const Extends = ");
        try names.writeRawIdent(writer, resolver.zigClassName(base_name));
        try writer.writeAll(";\n\n");
        try imports.add(base_name);
    } else {
        try writer.writeAll("    pub const Extends = void;\n\n");
    }

    try writeClassConstants(writer, arena, resolver, info);
    try writer.writeAll("\n");

    for (class.enums) |class_enum| {
        try writeClassEnum(writer, arena, class_enum);
        try writer.writeAll("\n");
    }

    try writeClassSignals(writer, arena, resolver, info, real_name, class, sections, &imports);
    try writeClassProperties(writer, arena, resolver, info, real_name, sections, &imports);

    if (class.is_instantiable and !singleton) {
        try class_templates.writeConstruct(writer, class);
    }

    var emitted_names: [4096][]const u8 = undefined;
    var emitted_count: usize = 0;

    var has_virtual = false;
    for (class.methods) |method| {
        if (method.is_virtual) has_virtual = true;
    }
    if (has_virtual) try writeVirtualStruct(writer, arena, resolver, class, info, real_name, sections, &imports);

    for (class.methods) |*method| {
        if (method.is_virtual) {
            if (!method.is_required) {
                try writeOwnMethod(writer, arena, resolver, class, method, real_name, sections, resolver.virtualName(info, method.name), &imports);
                emitted_names[emitted_count] = method.name;
                emitted_count += 1;
            }
            continue;
        }
        if (method.is_vararg) {
            try writeVarargMethod(writer, arena, resolver, class, method, real_name, &imports);
            emitted_names[emitted_count] = method.name;
            emitted_count += 1;
            continue;
        }
        try writeOwnMethod(writer, arena, resolver, class, method, real_name, sections, null, &imports);
        emitted_names[emitted_count] = method.name;
        emitted_count += 1;
    }

    // Forward non-virtual methods from the inheritance chain.
    var base_info = resolver.baseInfo(info);
    while (base_info) |base| {
        try imports.add(base.class.name);
        for (base.class.methods) |*method| {
            if (method.is_virtual) {
                if (method.is_required) continue;
                if (hasMethodName(emitted_names[0..emitted_count], method.name)) continue;
                try writeForwardedMethod(writer, arena, resolver, class, base.class, method, real_name, resolver.virtualName(info, method.name), resolver.virtualName(base, method.name), &imports);
                emitted_names[emitted_count] = method.name;
                emitted_count += 1;
                continue;
            }
            if (hasMethodName(emitted_names[0..emitted_count], method.name)) continue;
            if (method.is_vararg) {
                try writeForwardedVarargMethod(writer, arena, resolver, class, base.class, method, real_name, &imports);
            } else {
                try writeForwardedMethod(writer, arena, resolver, class, base.class, method, real_name, null, null, &imports);
            }
            emitted_names[emitted_count] = method.name;
            emitted_count += 1;
        }
        base_info = resolver.baseInfo(base);
    }

    try custom_code.writeIndented(writer, sections.codeForStruct(class.name), 4);
    try writer.writeAll("};\n\n");
    try custom_code.writeRaw(writer, sections.namespace_code);

    try writeImports(writer, arena, resolver, info, &imports);
}

fn isSingleton(api: ExtensionApiJson, name: []const u8) bool {
    for (api.singletons) |singleton| {
        if (std.mem.eql(u8, singleton.type, name)) return true;
    }
    return false;
}

fn writeVirtualStruct(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const class_resolver.ClassResolver,
    class: *const ExtensionApiJson.Class,
    info: *const class_resolver.Info,
    real_name: []const u8,
    sections: custom_code.Sections,
    imports: *ImportSet,
) !void {
    try writer.writeAll("    pub const Virtual = struct {\n");
    try writeVirtualGroup(writer, arena, resolver, class, info, real_name, sections, imports, true);
    try writeVirtualGroup(writer, arena, resolver, class, info, real_name, sections, imports, false);
    try custom_code.writeIndented(writer, sections.codeForStruct("Virtual"), 4);
    try writer.writeAll("    };\n\n");
}

fn writeVirtualGroup(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const class_resolver.ClassResolver,
    class: *const ExtensionApiJson.Class,
    info: *const class_resolver.Info,
    real_name: []const u8,
    sections: custom_code.Sections,
    imports: *ImportSet,
    required: bool,
) !void {
    const group_name = if (required) "Required" else "Optional";
    try writer.print("        pub const {s} = struct {{\n", .{group_name});
    for (class.methods) |*method| {
        if (!method.is_virtual or method.is_required != required) continue;
        try docs.write(writer, arena, method.description, 12, "///");
        try writer.writeAll("            pub const ");
        try names.writeRawIdent(writer, resolver.virtualName(info, method.name));
        try writer.writeAll(" = *const fn (");
        var first = true;
        if (!method.is_static) {
            try writer.writeAll("self: *const ");
            try names.writeRawIdent(writer, class.name);
            first = false;
        }
        for (method.arguments) |argument| {
            if (!first) try writer.writeAll(", ");
            first = false;
            try names.writeArgName(writer, argument.name, 0);
            try writer.writeAll(": ");
            try resolveWrite(writer, resolver, argument.type, .argument, real_name);
            try addImportResolved(imports, resolver, argument.type, .argument);
        }
        try writer.writeAll(") callconv(.c) ");
        if (method.return_value) |return_value| {
            try resolveWrite(writer, resolver, return_value.type, .return_value, real_name);
            try addImportResolved(imports, resolver, return_value.type, .return_value);
        } else {
            try writer.writeAll("void");
        }
        try writer.writeAll(";\n");
    }
    const group_code = if (required) sections.codeForStruct("Required") else sections.codeForStruct("Optional");
    try custom_code.writeIndented(writer, group_code, 4);
    try writer.writeAll("        };\n\n");
}

fn writeClassConstants(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const class_resolver.ClassResolver,
    info: *const class_resolver.Info,
) !void {
    var seen: [512][]const u8 = undefined;
    var seen_count: usize = 0;
    var current: ?*const class_resolver.Info = info;
    while (current) |class_info| {
        for (class_info.class.constants) |constant| {
            if (hasMethodName(seen[0..seen_count], constant.name)) continue;
            seen[seen_count] = constant.name;
            seen_count += 1;
            try docs.write(writer, arena, constant.description, 4, "///");
            try writer.writeAll("    pub const ");
            try common.writeIdent(writer, .snake, constant.name);
            try writer.print(": i64 = {d};\n", .{constant.value});
        }
        current = resolver.baseInfo(class_info);
    }
}

fn writeClassSignals(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const class_resolver.ClassResolver,
    info: *const class_resolver.Info,
    real_name: []const u8,
    class: *const ExtensionApiJson.Class,
    sections: custom_code.Sections,
    imports: *ImportSet,
) !void {
    var seen: [2048][]const u8 = undefined;
    var seen_count: usize = 0;
    var current: ?*const class_resolver.Info = info;
    while (current) |class_info| {
        for (class_info.class.signals) |signal| {
            if (hasMethodName(seen[0..seen_count], signal.name)) continue;
            seen[seen_count] = signal.name;
            seen_count += 1;
            try writeClassSignal(writer, arena, resolver, class, signal, real_name, sections, imports);
        }
        current = resolver.baseInfo(class_info);
    }
}

fn writeClassSignal(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const class_resolver.ClassResolver,
    class: *const ExtensionApiJson.Class,
    signal: ExtensionApiJson.ClassSignal,
    real_name: []const u8,
    sections: custom_code.Sections,
    imports: *ImportSet,
) !void {
    try docs.write(writer, arena, signal.description, 4, "///");
    const signal_type = try names.pascal(arena, signal.name);
    try writer.writeAll("    pub const ");
    try names.writeRawIdent(writer, signal_type);
    try writer.writeAll(" = struct {\n");
    try writer.writeAll("        pub const signal_name = \"");
    try names.writeEscaped(writer, signal.name);
    try writer.writeAll("\";\n");

    for (signal.arguments) |argument| {
        try writer.writeAll("        ");
        try names.writeMemberIdent(writer, argument.name);
        try writer.writeAll(": ?");
        try resolveWrite(writer, resolver, argument.type, .argument, real_name);
        try writer.writeAll(" = null,\n");
        try addImportResolved(imports, resolver, argument.type, .argument);
    }

    try writer.writeAll("\n");
    try writer.writeAll("        pub fn connect(self: *");
    try names.writeRawIdent(writer, class.name);
    try writer.writeAll(", dispatcher: anytype, p_callable: builtins.Callable, opt: ");
    if (std.mem.eql(u8, class.name, "Object")) {
        try writer.writeAll("ConnectOptions");
    } else {
        try writer.writeAll("Object.ConnectOptions");
    }
    try writer.writeAll(") enums.Error {\n");
    try writer.writeAll("            return self.connect(dispatcher, StringName.fromComptimeLatin1(dispatcher, \"");
    try names.writeEscaped(writer, signal.name);
    try writer.writeAll("\"), p_callable, opt);\n");
    try writer.writeAll("        }\n\n");

    try writer.writeAll("        pub fn disconnect(self: *");
    try names.writeRawIdent(writer, class.name);
    try writer.writeAll(", dispatcher: anytype, p_callable: builtins.Callable) void {\n");
    try writer.writeAll("            self.disconnect(dispatcher, StringName.fromComptimeLatin1(dispatcher, \"");
    try names.writeEscaped(writer, signal.name);
    try writer.writeAll("\"), p_callable);\n");
    try writer.writeAll("        }\n\n");

    try writer.writeAll("        pub fn isConnected(self: *");
    try names.writeRawIdent(writer, class.name);
    try writer.writeAll(", dispatcher: anytype, p_callable: builtins.Callable) bool {\n");
    try writer.writeAll("            return self.isConnected(dispatcher, StringName.fromComptimeLatin1(dispatcher, \"");
    try names.writeEscaped(writer, signal.name);
    try writer.writeAll("\"), p_callable);\n");
    try writer.writeAll("        }\n");
    try custom_code.writeIndented(writer, sections.codeForStruct(signal_type), 4);
    try writer.writeAll("    };\n\n");
}

fn writeClassProperties(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const class_resolver.ClassResolver,
    info: *const class_resolver.Info,
    real_name: []const u8,
    sections: custom_code.Sections,
    imports: *ImportSet,
) !void {
    var has_any = false;
    var current: ?*const class_resolver.Info = info;
    while (current) |class_info| {
        if (class_info.class.properties.len != 0) {
            has_any = true;
            break;
        }
        current = resolver.baseInfo(class_info);
    }
    if (!has_any) return;

    try writer.writeAll("    pub const Properties = struct {\n");
    var seen: [2048][]const u8 = undefined;
    var seen_count: usize = 0;
    current = info;
    while (current) |class_info| {
        for (class_info.class.properties) |property| {
            if (hasMethodName(seen[0..seen_count], property.name)) continue;
            seen[seen_count] = property.name;
            seen_count += 1;
            try writeClassProperty(writer, arena, resolver, property, real_name, sections, imports);
        }
        current = resolver.baseInfo(class_info);
    }
    try custom_code.writeIndented(writer, sections.codeForStruct("Properties"), 4);
    try writer.writeAll("    };\n\n");
}

fn writeClassProperty(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const class_resolver.ClassResolver,
    property: ExtensionApiJson.ClassProperty,
    real_name: []const u8,
    sections: custom_code.Sections,
    imports: *ImportSet,
) !void {
    try docs.write(writer, arena, property.description, 8, "///");
    try writer.writeAll("        pub const ");
    try names.writeMemberIdent(writer, property.name);
    try writer.writeAll(" = struct {\n");
    try writer.writeAll("            pub const Type = ");
    if (std.mem.indexOfScalar(u8, property.type, ',') != null) {
        try writer.writeAll("builtins.Variant");
    } else {
        try resolveWrite(writer, resolver, property.type, .return_value, real_name);
        try addImportResolved(imports, resolver, property.type, .return_value);
    }
    try writer.writeAll(";\n");
    try writer.writeAll("            pub const getter: ?[]const u8 = ");
    try writeOptionalString(writer, property.getter);
    try writer.writeAll(";\n");
    try writer.writeAll("            pub const setter: ?[]const u8 = ");
    try writeOptionalString(writer, property.setter);
    try writer.writeAll(";\n");
    try writer.writeAll("            pub const index: ?i64 = ");
    if (property.index) |index| {
        try writer.print("{d}", .{index});
    } else {
        try writer.writeAll("null");
    }
    try writer.writeAll(";\n");
    const property_type = try names.snake(arena, property.name);
    try custom_code.writeIndented(writer, sections.codeForStruct(property_type), 4);
    try writer.writeAll("        };\n\n");
}

