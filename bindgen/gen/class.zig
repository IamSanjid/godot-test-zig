fn writeDefaultValue(
    writer: *Io.Writer,
    resolver: *const class_resolver.ClassResolver,
    raw_type: []const u8,
    default_value: []const u8,
) !bool {
    const resolved = try resolver.resolve(raw_type, .argument);
    if (try defaults.writeMathLiteral(writer, "builtins.", raw_type, default_value)) return true;
    if (try defaults.writeStringLiteral(writer, "builtins.", raw_type, default_value, "dispatcher")) return true;
    if (std.mem.eql(u8, raw_type, "Variant")) {
        if (try defaults.writeVariantLiteral(writer, "builtins.", default_value, "dispatcher")) return true;
    }
    if (try defaults.writeEmptyContainer(writer, "builtins.", raw_type, default_value, "dispatcher")) return true;
    if (std.mem.startsWith(u8, raw_type, "typedarray::") and std.mem.indexOf(u8, default_value, "[]") != null) {
        try writer.writeAll("builtins.Array.init(dispatcher)");
        return true;
    }
    switch (resolved.kind) {
        .@"enum" => {
            if (resolved.is_bitfield) {
                try writer.writeAll("@as(");
                try writer.writeAll(resolved.zig);
                try writer.writeAll(", @bitCast(@as(u32, ");
                try writer.writeAll(default_value);
                try writer.writeAll(")))");
            } else {
                try writer.writeAll("@as(");
                try writer.writeAll(resolved.zig);
                try writer.writeAll(", @fromBackingInt(@intCast(");
                try writer.writeAll(default_value);
                try writer.writeAll(")))");
            }
            return true;
        },
        .primitive => {
            try writer.writeAll(default_value);
            return true;
        },
        .variant => {
            try writer.writeAll("std.mem.zeroes(builtins.Variant)");
            return false;
        },
        .class_ptr => {
            try writer.writeAll("null");
            return std.mem.eql(u8, default_value, "null");
        },
        .native_ptr => {
            try writer.writeAll("null");
            return std.mem.eql(u8, default_value, "null");
        },
        .builtin => {
            try writer.writeAll(resolved.zig);
            try writer.writeAll(".init(dispatcher)");
            return defaults.isEmptyConstructor(raw_type, default_value);
        },
        .void => {
            try writer.writeAll("{}");
            return true;
        },
    }
}

fn hasMethodName(names_list: []const []const u8, name: []const u8) bool {
    for (names_list) |existing| {
        if (std.mem.eql(u8, existing, name)) return true;
    }
    return false;
}

fn resolveWrite(
    writer: *Io.Writer,
    resolver: *const class_resolver.ClassResolver,
    raw: []const u8,
    context: class_resolver.TypeContext,
    real_name: []const u8,
) !void {
    _ = real_name;
    const resolved = try resolver.resolve(raw, context);
    try writer.writeAll(resolved.zig);
}

fn addImport(
    imports: *ImportSet,
    resolver: *const class_resolver.ClassResolver,
    raw: []const u8,
) !void {
    if (resolver.get(raw)) |info| try imports.add(info.class.name);
}

fn addImportResolved(
    imports: *ImportSet,
    resolver: *const class_resolver.ClassResolver,
    raw: []const u8,
    context: class_resolver.TypeContext,
) !void {
    const resolved = try resolver.resolve(raw, context);
    if (resolved.import_class) |name| try imports.add(name);
    if (resolved.import_native) imports.native = true;
}

const ImportSet = struct {
    names: [512][]const u8 = undefined,
    count: usize = 0,
    native: bool = false,

    fn add(self: *ImportSet, name: []const u8) !void {
        for (self.names[0..self.count]) |existing| {
            if (std.mem.eql(u8, existing, name)) return;
        }
        if (self.count == self.names.len) return error.TooManyImports;
        self.names[self.count] = name;
        self.count += 1;
    }
};

fn writeImports(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const class_resolver.ClassResolver,
    info: *const class_resolver.Info,
    imports: *const ImportSet,
) !void {
    const prefix = try resolver.rootPrefix(arena, info);
    try writer.print("const builtins = @import(\"{s}builtins/builtins.zig\");\n", .{prefix});
    try writer.print("const enums = @import(\"{s}enums.zig\");\n", .{prefix});
    try writer.print("const constants = @import(\"{s}constants.zig\");\n", .{prefix});
    try writer.print("const interface = @import(\"{s}interface.zig\");\n", .{prefix});
    if (imports.native) try writer.print("const native = @import(\"{s}native.zig\");\n", .{prefix});
    try writer.writeAll("const StringName = builtins.StringName;\n");
    try writer.writeAll("const std = @import(\"std\");\n");

    const current_alias = resolver.zigClassName(info.class.name);
    if (!std.mem.eql(u8, current_alias, info.class.name)) {
        try writer.print("const {s} = {s};\n", .{ current_alias, info.class.name });
    }

    for (imports.names[0..imports.count]) |name| {
        if (std.mem.eql(u8, name, info.class.name)) continue;
        const other = resolver.get(name) orelse continue;
        const rel = try resolver.relativeClassImport(arena, info, other);
        try writer.print("const {s} = @import(\"{s}\").{s};\n", .{ resolver.zigClassName(name), rel, name });
    }
}

