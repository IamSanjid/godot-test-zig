fn writeOwnMethod(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const class_resolver.ClassResolver,
    class: *const ExtensionApiJson.Class,
    method: *const ExtensionApiJson.ClassMethod,
    real_name: []const u8,
    sections: custom_code.Sections,
    override_name: ?[]const u8,
    imports: *ImportSet,
) !void {
    const method_pascal = try names.pascal(arena, method.name);

    var has_options = false;
    for (method.arguments) |argument| {
        if (argument.default_value != null) has_options = true;
    }
    if (has_options) try writeOptions(writer, arena, resolver, method, method_pascal, real_name, sections, imports);

    try docs.write(writer, arena, method.description, 4, "///");
    try writer.writeAll("    pub fn ");
    if (override_name) |name| {
        try names.writeRawIdent(writer, name);
    } else {
        try common.writeIdent(writer, .camel, method.name);
    }
    try writer.writeAll("(");
    if (!method.is_static) {
        try writer.writeAll("self: *");
        if (method.is_const) try writer.writeAll("const ");
        try names.writeRawIdent(writer, class.name);
        try writer.writeAll(", dispatcher: anytype");
    } else {
        try writer.writeAll("dispatcher: anytype");
    }
    for (method.arguments) |argument| {
        if (argument.default_value != null) continue;
        try writer.writeAll(", ");
        try names.writeArgName(writer, argument.name, 0);
        try writer.writeAll(": ");
        try resolveWrite(writer, resolver, argument.type, .argument, real_name);
        try addImport(imports, resolver, argument.type);
        try addImportResolved(imports, resolver, argument.type, .argument);
    }
    if (has_options) {
        try writer.writeAll(", opt: ");
        try writer.writeAll(method_pascal);
        try writer.writeAll("Options");
    }
    try writer.writeAll(") ");
    const return_type = if (method.return_value) |return_value| return_value.type else "void";
    const resolved_return = try resolver.resolve(return_type, .return_value);
    try addImportResolved(imports, resolver, return_type, .return_value);
    try writer.writeAll(resolved_return.zig);
    try writer.writeAll(" {\n");

    for (method.arguments) |argument| {
        if (argument.default_value) |default_value| {
            const needs_deinit = std.mem.eql(u8, argument.type, "String");
            try writer.writeAll(if (needs_deinit) "        var " else "        const ");
            try names.writePrefixedIdent(writer, "actual_", argument.name);
            try writer.writeAll(" = opt.");
            try names.writeMemberIdent(writer, argument.name);
            try writer.writeAll(" orelse ");
            const parsed_default = try writeDefaultValue(writer, resolver, argument.type, default_value);
            try writer.writeAll(";\n");
            if (!parsed_default) {
                std.log.warn("Could not reconstruct default for {s}.{s}({s}): value `{s}` of type `{s}`", .{
                    class.name, method.name, argument.name, default_value, argument.type,
                });
            }
            if (needs_deinit) {
                try writer.writeAll("        defer ");
                try names.writePrefixedIdent(writer, "actual_", argument.name);
                try writer.writeAll(".deinit(dispatcher);\n");
            }
        }
    }

    try writer.print("        var args: [{d}]interface.ConstTypePtr = undefined;\n", .{method.arguments.len});
    for (method.arguments, 0..) |argument, index| {
        const has_default = argument.default_value != null;
        const resolved_argument = try resolver.resolve(argument.type, .argument);
        if (resolved_argument.kind == .@"enum") {
            if (resolved_argument.is_bitfield) {
                try writer.print("        const arg{d}_slot: u32 = @bitCast(", .{index});
                if (has_default) {
                    try names.writePrefixedIdent(writer, "actual_", argument.name);
                } else {
                    try names.writeArgName(writer, argument.name, 0);
                }
                try writer.writeAll(");\n");
                try writer.print("        args[{d}] = @ptrCast(&arg{d}_slot);\n", .{ index, index });
            } else {
                try writer.print("        const arg{d}_slot: i64 = @backingInt(", .{index});
                if (has_default) {
                    try names.writePrefixedIdent(writer, "actual_", argument.name);
                } else {
                    try names.writeArgName(writer, argument.name, 0);
                }
                try writer.writeAll(");\n");
                try writer.print("        args[{d}] = @ptrCast(&arg{d}_slot);\n", .{ index, index });
            }
        } else {
            try writer.print("        args[{d}] = @ptrCast(&", .{index});
            if (has_default) {
                try names.writePrefixedIdent(writer, "actual_", argument.name);
            } else {
                try names.writeArgName(writer, argument.name, 0);
            }
            try writer.writeAll(");\n");
        }
        try addImport(imports, resolver, argument.type);
        try addImportResolved(imports, resolver, argument.type, .argument);
    }

    const is_enum_return = resolved_return.kind == .@"enum";
    if (is_enum_return) {
        if (resolved_return.is_bitfield) {
            try writer.writeAll("        var result: u32 = undefined;\n");
        } else {
            try writer.writeAll("        var result: i64 = undefined;\n");
        }
    } else if (resolved_return.kind != .void) {
        try writer.writeAll("        var result: ");
        try writer.writeAll(resolved_return.zig);
        try writer.writeAll(" = undefined;\n");
    }

    const ptr_source = if (override_name != null) try std.fmt.allocPrint(arena, "{s}_virtual", .{method.name}) else method.name;
    const ptr_name = try names.pointer(arena, ptr_source);
    try writer.print("        if ({s} == null) {{\n", .{ptr_name});
    try writer.writeAll("            @branchHint(.cold);\n");
    try writer.writeAll("            var class_name = StringName.fromComptimeLatin1(dispatcher, \"");
    try names.writeEscaped(writer, class.name);
    try writer.writeAll("\");\n");
    try writer.writeAll("            var method_name = StringName.fromComptimeLatin1(dispatcher, \"");
    try names.writeEscaped(writer, method.name);
    try writer.writeAll("\");\n");
    try writer.print("            {s} = dispatcher.dispatch(.classdb_get_method_bind, .{{ @ptrCast(&class_name), @ptrCast(&method_name), {d} }});\n", .{ ptr_name, method.hash });
    if (method.hash_compatibility.len != 0) {
        try writer.writeAll("            inline for ([_]u32{");
        for (method.hash_compatibility, 0..) |hash, index| {
            if (index != 0) try writer.writeAll(", ");
            try writer.print("{d}", .{hash});
        }
        try writer.writeAll("}) |compat_hash| {\n");
        try writer.print("                if ({s} == null) {s} = dispatcher.dispatch(.classdb_get_method_bind, .{{ @ptrCast(&class_name), @ptrCast(&method_name), compat_hash }});\n", .{ ptr_name, ptr_name });
        try writer.writeAll("            }\n");
    }
    try writer.print("            if ({s} == null) @panic(\"", .{ptr_name});
    try names.writeEscaped(writer, class.name);
    try writer.writeAll(".");
    try names.writeEscaped(writer, method.name);
    try writer.writeAll(" was not found\");\n");
    try writer.writeAll("        }\n");

    try writer.print("        dispatcher.dispatch(.object_method_bind_ptrcall, .{{ {s}, ", .{ptr_name});
    if (method.is_static) {
        try writer.writeAll("null");
    } else {
        try writer.writeAll(if (method.is_const) "@ptrCast(@constCast(self))" else "@ptrCast(self)");
    }
    try writer.writeAll(", @ptrCast(&args), ");
    if (resolved_return.kind == .void) {
        try writer.writeAll("null");
    } else {
        try writer.writeAll("@ptrCast(&result)");
    }
    try writer.writeAll(" });\n");

    switch (resolved_return.kind) {
        .void => {},
        .@"enum" => {
            if (resolved_return.is_bitfield) {
                try writer.writeAll("        return @bitCast(result);\n");
            } else {
                try writer.writeAll("        return @fromBackingInt(@intCast(result));\n");
            }
        },
        else => try writer.writeAll("        return result;\n"),
    }
    try writer.writeAll("    }\n");
    try writer.print("    var {s}: interface.MethodBindPtr = null;\n\n", .{ptr_name});
}

fn writeVarargMethod(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const class_resolver.ClassResolver,
    class: *const ExtensionApiJson.Class,
    method: *const ExtensionApiJson.ClassMethod,
    real_name: []const u8,
    imports: *ImportSet,
) !void {
    const fixed_count = method.arguments.len;

    try docs.write(writer, arena, method.description, 4, "///");
    try writer.writeAll("    pub fn ");
    try common.writeIdent(writer, .camel, method.name);
    try writer.writeAll("(");
    if (!method.is_static) {
        try writer.writeAll("self: *");
        if (method.is_const) try writer.writeAll("const ");
        try names.writeRawIdent(writer, class.name);
        try writer.writeAll(", dispatcher: anytype");
    } else {
        try writer.writeAll("dispatcher: anytype");
    }
    for (method.arguments) |argument| {
        try writer.writeAll(", ");
        try names.writeArgName(writer, argument.name, 0);
        try writer.writeAll(": ");
        try resolveWrite(writer, resolver, argument.type, .argument, real_name);
        try addImportResolved(imports, resolver, argument.type, .argument);
    }
    try writer.writeAll(", vargs: anytype) ");
    const return_type = if (method.return_value) |return_value| return_value.type else "void";
    const resolved_return = try resolver.resolve(return_type, .return_value);
    try addImportResolved(imports, resolver, return_type, .return_value);
    try writer.writeAll(resolved_return.zig);
    try writer.writeAll(" {\n");

    if (fixed_count != 0) {
        try writer.print("        var fixed: [{d}]builtins.Variant = undefined;\n", .{fixed_count});
        for (method.arguments, 0..) |argument, index| {
            const resolved = try resolver.resolve(argument.type, .argument);
            try writer.print("        fixed[{d}] = ", .{index});
            if (resolved.kind == .class_ptr) {
                try writer.writeAll("builtins.Variant.fromPtr(dispatcher, @TypeOf(");
                try names.writeArgName(writer, argument.name, 0);
                try writer.writeAll(".*), ");
                try names.writeArgName(writer, argument.name, 0);
                try writer.writeAll(");\n");
            } else if (resolved.kind == .variant) {
                try names.writeArgName(writer, argument.name, 0);
                try writer.writeAll(";\n");
            } else {
                try writer.writeAll("builtins.Variant.fromPtr(dispatcher, @TypeOf(");
                try names.writeArgName(writer, argument.name, 0);
                try writer.writeAll("), &");
                try names.writeArgName(writer, argument.name, 0);
                try writer.writeAll(");\n");
            }
            try addImport(imports, resolver, argument.type);
            try addImportResolved(imports, resolver, argument.type, .argument);
        }
        try writer.print("        var args: [{d} + vargs.len]*builtins.Variant = undefined;\n", .{fixed_count});
        for (0..fixed_count) |index| {
            try writer.print("        args[{d}] = &fixed[{d}];\n", .{ index, index });
        }
    } else {
        try writer.writeAll("        var args: [vargs.len]*builtins.Variant = undefined;\n");
    }
    try writer.writeAll("        inline for (0..vargs.len) |i| {\n");
    try writer.writeAll("            if (@TypeOf(vargs[i]) != builtins.Variant) @compileError(\"vargs: should only contain 'Variant' types.\");\n");
    try writer.print("            args[{d} + i] = @constCast(&vargs[i]);\n", .{fixed_count});
    try writer.writeAll("        }\n");

    var result_is_void = false;
    if (resolved_return.kind == .void) {
        result_is_void = true;
    } else {
        try writer.writeAll("        var result: builtins.Variant = builtins.Variant.nil();\n");
        try writer.writeAll("        var err: interface.CallError = undefined;\n");
    }

    const ptr_name = try names.pointer(arena, method.name);
    try writer.print("        if ({s} == null) {{\n", .{ptr_name});
    try writer.writeAll("            @branchHint(.cold);\n");
    try writer.writeAll("            var class_name = StringName.fromComptimeLatin1(dispatcher, \"");
    try names.writeEscaped(writer, class.name);
    try writer.writeAll("\");\n");
    try writer.writeAll("            var method_name = StringName.fromComptimeLatin1(dispatcher, \"");
    try names.writeEscaped(writer, method.name);
    try writer.writeAll("\");\n");
    try writer.print("            {s} = dispatcher.dispatch(.classdb_get_method_bind, .{{ @ptrCast(&class_name), @ptrCast(&method_name), {d} }});\n", .{ ptr_name, method.hash });
    if (method.hash_compatibility.len != 0) {
        try writer.writeAll("            inline for ([_]u32{");
        for (method.hash_compatibility, 0..) |hash, index| {
            if (index != 0) try writer.writeAll(", ");
            try writer.print("{d}", .{hash});
        }
        try writer.writeAll("}) |compat_hash| {\n");
        try writer.print("                if ({s} == null) {s} = dispatcher.dispatch(.classdb_get_method_bind, .{{ @ptrCast(&class_name), @ptrCast(&method_name), compat_hash }});\n", .{ ptr_name, ptr_name });
        try writer.writeAll("            }\n");
    }
    try writer.print("            if ({s} == null) @panic(\"", .{ptr_name});
    try names.writeEscaped(writer, class.name);
    try writer.writeAll(".");
    try names.writeEscaped(writer, method.name);
    try writer.writeAll(" was not found\");\n");
    try writer.writeAll("        }\n");

    try writer.print("        dispatcher.dispatch(.object_method_bind_call, .{{ {s}, ", .{ptr_name});
    if (method.is_static) {
        try writer.writeAll("null");
    } else {
        try writer.writeAll(if (method.is_const) "@ptrCast(@constCast(self))" else "@ptrCast(self)");
    }
    try writer.writeAll(", @ptrCast(&args), @intCast(args.len), ");
    if (result_is_void) {
        try writer.writeAll("null");
    } else {
        try writer.writeAll("@ptrCast(&result)");
    }
    try writer.writeAll(", ");
    if (result_is_void) {
        try writer.writeAll("null");
    } else {
        try writer.writeAll("&err");
    }
    try writer.writeAll(" });\n");

    switch (resolved_return.kind) {
        .void => {},
        .variant => try writer.writeAll("        return result;\n"),
        .@"enum" => try writer.writeAll("        return @fromBackingInt(@intCast(result.asInt()));\n"),
        else => try writer.writeAll("        return result;\n"),
    }
    try writer.writeAll("    }\n");
    try writer.print("    var {s}: interface.MethodBindPtr = null;\n\n", .{ptr_name});
}

