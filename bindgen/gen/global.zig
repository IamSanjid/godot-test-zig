//! Global constants and global enum emission for `extension_api.json`.

pub fn generate(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
) !void {
    try writeConstants(arena, io, api, options);
    try writeEnums(arena, io, api, options);
}

fn writeConstants(arena: Allocator, io: Io, api: ExtensionApiJson, options: Options) !void {
    const path = try std.fs.path.join(arena, &.{ options.output_dir, "constants.zig" });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create constants file `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush constants file `{s}`: {}", .{ path, err });
    };

    try emitConstants(&streaming.interface, arena, api);
    try appendNamespace(&streaming.interface, arena, io, "constants.zig");
}

fn writeEnums(arena: Allocator, io: Io, api: ExtensionApiJson, options: Options) !void {
    const path = try std.fs.path.join(arena, &.{ options.output_dir, "enums.zig" });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create enums file `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush enums file `{s}`: {}", .{ path, err });
    };

    try emitEnums(&streaming.interface, arena, api);
    try appendNamespace(&streaming.interface, arena, io, "enums.zig");
}

fn emitConstants(writer: *Io.Writer, arena: Allocator, api: ExtensionApiJson) !void {
    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    for (api.global_constants) |constant| {
        try docs.write(writer, arena, constant.description, 0, "///");
        try writer.writeAll("pub const ");
        try common.writeIdent(writer, .snake, constant.name);
        try writer.print(" = {d};\n", .{constant.value});
    }
}

fn emitEnums(writer: *Io.Writer, arena: Allocator, api: ExtensionApiJson) !void {
    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    for (api.global_enums) |global_enum| {
        try writeEnum(writer, arena, global_enum);
        try writer.writeAll("\n");
    }
}

fn appendNamespace(writer: *Io.Writer, arena: Allocator, io: Io, relative_path: []const u8) !void {
    const sections = (try custom_code.readForOutput(arena, io, relative_path)) orelse custom_code.Sections{};
    if (sections.namespace_code.len != 0) {
        try writer.writeAll("\n");
        try custom_code.writeRaw(writer, sections.namespace_code);
    }
}

fn writeEnum(writer: *Io.Writer, arena: Allocator, global_enum: ExtensionApiJson.GlobalEnum) !void {
    try enum_emit.write(writer, arena, global_enum, 0);
}

const std = @import("std");
const Allocator = std.mem.Allocator;
const Io = std.Io;

const common = @import("common.zig");
const enum_emit = @import("enum_emit.zig");
const custom_code = @import("custom.zig");
const docs = @import("docs.zig");
const enum_utils = @import("enum_utils.zig");
const ExtensionApiJson = @import("../ExtensionApiJson.zig");
const Options = @import("../Options.zig");
