//! Utility-function bindings, grouped by category.

pub fn generate(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const ClassResolver.Resolver,
) !void {
    const utility_dir = try std.fs.path.join(arena, &.{ options.output_dir, "utility" });
    Io.Dir.cwd().createDirPath(io, utility_dir) catch |err| {
        std.log.err("Failed to create utility directory `{s}`: {}", .{ utility_dir, err });
        return err;
    };

    var categories: [32][]const u8 = undefined;
    var category_count: usize = 0;
    for (api.utility_functions) |function| {
        var seen = false;
        for (categories[0..category_count]) |category| {
            if (std.mem.eql(u8, category, function.category)) {
                seen = true;
                break;
            }
        }
        if (seen) continue;
        categories[category_count] = function.category;
        category_count += 1;
    }
    std.mem.sort([]const u8, categories[0..category_count], {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.order(u8, a, b) == .lt;
        }
    }.lessThan);

    for (categories[0..category_count]) |category| {
        try writeCategory(arena, io, api, options, resolver, category);
    }
    try writeAggregator(arena, io, options, categories[0..category_count]);
}

fn writeCategory(
    arena: Allocator,
    io: Io,
    api: ExtensionApiJson,
    options: Options,
    resolver: *const ClassResolver.Resolver,
    category: []const u8,
) !void {
    const file_name = try names.snake(arena, category);
    const relative_path = try std.fmt.allocPrint(arena, "utility/{s}.zig", .{file_name});
    const full_path = try std.fs.path.join(arena, &.{ options.output_dir, relative_path });
    const file = Io.Dir.cwd().createFile(io, full_path, .{}) catch |err| {
        std.log.err("Failed to create utility file `{s}`: {}", .{ full_path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush utility file `{s}`: {}", .{ full_path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    for (api.utility_functions) |function| {
        if (!std.mem.eql(u8, function.category, category)) continue;
        try writeFunction(writer, arena, resolver, function);
    }

    const sections = (try custom_code.readForOutput(arena, io, relative_path)) orelse custom_code.Sections{};
    try custom_code.writeRaw(writer, sections.namespace_code);
    try writer.writeAll("\nconst builtins = @import(\"../builtins/builtins.zig\");\n");
    try writer.writeAll("const classes = @import(\"../classes/classes.zig\");\n");
    try writer.writeAll("const interface = @import(\"../interface.zig\");\n");
    try writer.writeAll("const enums = @import(\"../enums.zig\");\n");
    try writer.writeAll("const StringName = builtins.StringName;\n");
}

fn writeAggregator(
    arena: Allocator,
    io: Io,
    options: Options,
    categories: []const []const u8,
) !void {
    const path = try std.fs.path.join(arena, &.{ options.output_dir, "utility", "utility.zig" });
    const file = Io.Dir.cwd().createFile(io, path, .{}) catch |err| {
        std.log.err("Failed to create utility aggregator `{s}`: {}", .{ path, err });
        return err;
    };
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var streaming = file.writerStreaming(io, &buffer);
    defer streaming.flush() catch |err| {
        std.log.err("Failed to flush utility aggregator `{s}`: {}", .{ path, err });
    };
    const writer = &streaming.interface;

    try writer.writeAll("// Generated by bindgen. Do not edit.\n\n");
    for (categories) |category| {
        const file_name = try names.snake(arena, category);
        try writer.writeAll("pub const ");
        try common.writeIdent(writer, .snake, category);
        try writer.print(" = @import(\"{s}.zig\");\n", .{file_name});
    }

    const sections = (try custom_code.readForOutput(arena, io, "utility/utility.zig")) orelse custom_code.Sections{};
    try custom_code.writeRaw(writer, sections.namespace_code);
}

fn writeFunction(
    writer: *Io.Writer,
    arena: Allocator,
    resolver: *const ClassResolver.Resolver,
    function: ExtensionApiJson.UtilityFunction,
) !void {
    try docs.write(writer, arena, function.description, 0, "///");
    try writer.writeAll("pub fn ");
    try common.writeIdent(writer, .camel, function.name);
    try writer.writeAll("(dispatcher: anytype");
    for (function.arguments) |argument| {
        try writer.writeAll(", ");
        try names.writeArgName(writer, argument.name, 0);
        try writer.writeAll(": ");
        try resolveType(writer, resolver, argument.type, .argument);
    }
    if (function.is_vararg) try writer.writeAll(", vargs: anytype");
    try writer.writeAll(") ");
    const return_type = function.return_type orelse "void";
    const resolved_return = try resolver.resolve(return_type, .return_value);
    try resolveType(writer, resolver, return_type, .return_value);
    try writer.writeAll(" {\n");

    try writer.print("    var args: [{d}", .{function.arguments.len});
    if (function.is_vararg) try writer.writeAll(" + vargs.len");
    try writer.writeAll("]interface.ConstTypePtr = undefined;\n");

    for (function.arguments, 0..) |argument, index| {
        const resolved = try resolver.resolve(argument.type, .argument);
        if (resolved.kind == .@"enum") {
            if (resolved.is_bitfield) {
                try writer.print("    const arg{d}_slot: u32 = @bitCast(", .{index});
            } else {
                try writer.print("    const arg{d}_slot: i64 = @backingInt(", .{index});
            }
            try names.writeArgName(writer, argument.name, 0);
            try writer.writeAll(");\n");
            try writer.print("    args[{d}] = @ptrCast(&arg{d}_slot);\n", .{ index, index });
        } else {
            try writer.print("    args[{d}] = @ptrCast(&", .{index});
            try names.writeArgName(writer, argument.name, 0);
            try writer.writeAll(");\n");
        }
    }

    if (function.is_vararg) {
        try writer.writeAll("    inline for (0..vargs.len) |i| {\n");
        try writer.writeAll("        if (@TypeOf(vargs[i]) != builtins.Variant) @compileError(\"vargs: should only contain 'Variant' types.\");\n");
        try writer.print("        args[{d} + i] = @ptrCast(&vargs[i]);\n", .{function.arguments.len});
        try writer.writeAll("    }\n");
    }

    if (resolved_return.kind != .void) {
        if (resolved_return.kind == .@"enum") {
            if (resolved_return.is_bitfield) {
                try writer.writeAll("    var result: u32 = undefined;\n");
            } else {
                try writer.writeAll("    var result: i64 = undefined;\n");
            }
        } else {
            try writer.writeAll("    var result: ");
            try resolveType(writer, resolver, return_type, .return_value);
            try writer.writeAll(" = undefined;\n");
        }
    }

    const ptr_name = try names.pointer(arena, function.name);
    try writer.print("    if ({s} == null) {{\n", .{ptr_name});
    try writer.writeAll("        @branchHint(.cold);\n");
    try writer.writeAll("        var function_name = StringName.fromComptimeLatin1(dispatcher, \"");
    try names.writeEscaped(writer, function.name);
    try writer.writeAll("\");\n");
    try writer.print("        {s} = dispatcher.dispatch(.variant_get_ptr_utility_function, .{{ @ptrCast(&function_name), {d} }});\n", .{ ptr_name, function.hash });
    if (function.hash_compatibility.len != 0) {
        try writer.writeAll("        inline for ([_]u32{");
        for (function.hash_compatibility, 0..) |hash, index| {
            if (index != 0) try writer.writeAll(", ");
            try writer.print("{d}", .{hash});
        }
        try writer.writeAll("}) |compat_hash| {\n");
        try writer.print("            if ({s} == null) {s} = dispatcher.dispatch(.variant_get_ptr_utility_function, .{{ @ptrCast(&function_name), compat_hash }});\n", .{ ptr_name, ptr_name });
        try writer.writeAll("        }\n");
    }
    try writer.print("        if ({s} == null) @panic(\"", .{ptr_name});
    try names.writeEscaped(writer, function.name);
    try writer.writeAll(" was not found\");\n");
    try writer.writeAll("    }\n");

    try writer.print("    {s}.?(", .{ptr_name});
    if (resolved_return.kind == .void) {
        try writer.writeAll("null");
    } else {
        try writer.writeAll("@ptrCast(&result)");
    }
    try writer.writeAll(", @ptrCast(&args), @intCast(args.len));\n");

    switch (resolved_return.kind) {
        .void => {},
        .@"enum" => {
            if (resolved_return.is_bitfield) {
                try writer.writeAll("    return @bitCast(result);\n");
            } else {
                try writer.writeAll("    return @fromBackingInt(@intCast(result));\n");
            }
        },
        else => try writer.writeAll("    return result;\n"),
    }
    try writer.writeAll("}\n");
    try writer.print("var {s}: interface.PtrUtilityFunction = null;\n\n", .{ptr_name});
}

fn resolveType(
    writer: *Io.Writer,
    resolver: *const ClassResolver.Resolver,
    raw: []const u8,
    context: ClassResolver.TypeContext,
) !void {
    const resolved = try resolver.resolve(raw, context);
    if (resolved.import_class) |class_name| {
        const info = resolver.get(class_name) orelse {
            try writer.writeAll(resolved.zig);
            return;
        };
        switch (resolved.kind) {
            .class_ptr => {
                if (std.mem.startsWith(u8, resolved.zig, "?*")) try writer.writeAll("?*") else try writer.writeAll("*");
                try writeClassRef(writer, info);
                return;
            },
            .@"enum" => {
                try writeClassRef(writer, info);
                const dot = std.mem.lastIndexOfScalar(u8, resolved.zig, '.') orelse {
                    return;
                };
                try writer.writeAll(resolved.zig[dot..]);
                return;
            },
            else => {},
        }
    }
    try writer.writeAll(resolved.zig);
}

fn writeClassRef(writer: *Io.Writer, info: *const ClassResolver.Info) !void {
    try writer.writeAll("classes.");
    if (info.class.api_type) |api_type| {
        try common.writeIdent(writer, .snake, api_type);
        try writer.writeAll(".");
    }
    try names.writeRawIdent(writer, info.class.name);
}

